/**
 * Import of a CSV file, end to end (1.9.0, D6): the file is read in the browser (UTF-8 only, refused and never
 * repaired), columns are chosen by the person, an empty field and some words are NULL, the whole file is validated
 * by the database without writing a row (the numbers are the file's rows, the header counted), and the import is
 * previewed and applied in one transaction: every row is added or none is. axe in both themes and on a phone.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import pg from "pg";
import type { Page } from "@playwright/test";
import { expect, test, type TestDb } from "./fixtures";

const axeSource = readFileSync(
  createRequire(import.meta.url).resolve("axe-core/axe.min.js"),
  "utf8",
);

async function sql<Row extends Record<string, unknown> = Record<string, unknown>>(
  database: TestDb,
  text: string,
): Promise<Row[]> {
  const c = new pg.Client({
    host: database.host,
    port: database.port,
    user: database.user,
    password: database.password,
    database: database.name,
  });
  await c.connect();
  try {
    return (await c.query(text)).rows as Row[];
  } finally {
    await c.end();
  }
}

async function axeInDialog(page: Page, name: string): Promise<void> {
  // A dialog that is still fading in has colours blended with the page behind it: wait for the end of the animation.
  await expect(page.locator('[role="dialog"]').first()).toHaveCSS("opacity", "1");
  await page.addScriptTag({ content: axeSource });
  const result = await page.evaluate(async () => {
    const axe = (
      window as unknown as {
        axe: {
          run: (
            c: Element,
            o: object,
          ) => Promise<{
            violations: Array<{
              id: string;
              impact: string | null;
              nodes: Array<{ target: unknown[]; html: string }>;
            }>;
          }>;
        };
      }
    ).axe;
    return axe.run(document.querySelector('[role="dialog"]') ?? document.body, {
      runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"] },
    });
  });
  const found = result.violations.map(
    (v) =>
      `${v.id} (${v.impact}): ${v.nodes
        .slice(0, 3)
        .map((n) => `${n.target.join(" ")} ${n.html.slice(0, 160)}`)
        .join(" | ")}`,
  );
  console.log(`axe ${name}: ${found.join(" || ")}`);
  expect.soft(found, `axe on ${name}`).toEqual([]);
}

const file = (text: string | Buffer, name = "people.csv") => ({
  name,
  mimeType: "text/csv",
  buffer: typeof text === "string" ? Buffer.from(text, "utf8") : text,
});
const dialogOf = (page: Page) => page.getByRole("dialog", { name: /Import a CSV file into/ });

test.describe("import", () => {
  test.beforeEach(async ({ page, writableApp, database }) => {
    await sql(
      database,
      `CREATE TABLE public.imp_people (
         id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
         full_name text NOT NULL,
         email text UNIQUE,
         qty integer CONSTRAINT qty_not_negative CHECK (qty >= 0),
         note text);`,
    );
    await page.goto(writableApp.link);
    await page.getByRole("button", { name: "Connect PostgreSQL" }).click();
    await page.getByLabel("Connection name").fill("Imp shop");
    await page.getByRole("tab", { name: /connection string/i }).click();
    await page.getByRole("textbox", { name: "Connection string" }).fill(database.url);
    await page.getByLabel("Allow viewing table data").check();
    await page.getByRole("button", { name: /^Connect$/ }).click();
    await expect(page.getByRole("button", { name: "Disconnect Imp shop" })).toBeVisible();
    await page.getByRole("switch", { name: "Allow changes to Imp shop" }).click();
    const unlock = page.getByRole("dialog");
    await unlock.getByRole("textbox", { name: "Database name" }).fill(database.name);
    await unlock.getByRole("button", { name: "Allow changes" }).click();
    await expect(page.getByText("Writes on")).toBeVisible();
    await page.getByRole("tab", { name: "Table details" }).click();
    await page
      .getByRole("button", { name: /^imp_people\b/ })
      .first()
      .click();
    // The table is empty: the Data section says so, and its toolbar is there.
    await expect(page.getByText("This table has no rows.")).toBeVisible();
    await page.getByRole("button", { name: "Import CSV" }).click();
    await expect(dialogOf(page)).toBeVisible();
  });

  test("reads a file, suggests the columns, reads NULL as asked, validates, and adds every row", async ({
    page,
    database,
  }) => {
    const dialog = dialogOf(page);
    // A byte order mark, a quoted comma, a quoted line break, an empty field and a word that means NULL.
    const text =
      "\uFEFFFull Name,Email,Qty,Note\r\n" +
      'Ann,ann@x.test,5,"says ""hi"", twice"\r\n' +
      'Bo,bo@x.test,,"two\nlines"\r\n' +
      "Cy,cy@x.test,7,n/a\r\n";
    await dialog.getByLabel("CSV file").setInputFiles(file(text));
    await expect(dialog.getByRole("status").first()).toContainText("3 rows, 4 columns");
    // The columns are suggested by name, without regard to case and spaces.
    await expect(dialog.getByLabel(/for file column 1, Full Name/)).toHaveValue("full_name");
    await expect(dialog.getByLabel(/for file column 2, Email/)).toHaveValue("email");
    await expect(dialog.getByLabel(/for file column 4, Note/)).toHaveValue("note");
    await dialog.getByLabel("n/a is NULL").check();
    // The preview of the first rows shows how they will be read.
    const firstRows = dialog.getByRole("table", { name: "The first rows of the import" });
    await expect(firstRows).toContainText("two");
    await expect(firstRows.getByText("NULL").first()).toBeVisible();

    await dialog.getByRole("button", { name: "Validate the file" }).click();
    await expect(dialog.getByRole("status", { name: "Check of the values" })).toContainText(
      "No problems found in 3 rows",
    );
    // Nothing is written by validating.
    expect(await sql(database, "SELECT count(*)::int AS n FROM public.imp_people")).toEqual([
      { n: 0 },
    ]);

    await dialog.getByRole("button", { name: "Preview the import" }).click();
    const preview = page.getByRole("dialog", { name: /Import 3 rows into public.imp_people/ });
    await expect(
      preview.getByText(/Adds 3 rows to "public"."imp_people"|Adds 3 rows to public.imp_people/),
    ).toBeVisible();
    await expect(preview.getByLabel("The statement that will run")).toContainText("unnest(");
    await preview.getByRole("button", { name: "Apply" }).click();
    await expect(page.getByText("3 rows were added.")).toBeVisible();
    expect(
      await sql(database, "SELECT full_name, email, qty, note FROM public.imp_people ORDER BY id"),
    ).toEqual([
      { full_name: "Ann", email: "ann@x.test", qty: 5, note: 'says "hi", twice' },
      { full_name: "Bo", email: "bo@x.test", qty: null, note: "two\nlines" },
      { full_name: "Cy", email: "cy@x.test", qty: 7, note: null },
    ]);
  });

  test("reads the empty string instead of NULL when asked, and a file with no header and another separator", async ({
    page,
    database,
  }) => {
    const dialog = dialogOf(page);
    await dialog.getByLabel("CSV file").setInputFiles(file("Ann;a@x.test;\nBo;b@x.test;x\n"));
    // The separator is found, and the first row is data once the box is cleared.
    await expect(dialog.getByLabel("Separator")).toContainText("Found: Semicolon");
    await dialog.getByLabel("The first row holds the column names").uncheck();
    await expect(dialog.getByRole("status").first()).toContainText("2 rows, 3 columns");
    await dialog.getByLabel(/for file column 1, Column 1/).selectOption("full_name");
    await dialog.getByLabel(/for file column 2, Column 2/).selectOption("email");
    await dialog.getByLabel(/for file column 3, Column 3/).selectOption("note");
    await dialog.getByLabel("An empty field is NULL (otherwise it is the empty string)").uncheck();
    await dialog.getByRole("button", { name: "Preview the import" }).click();
    await page
      .getByRole("dialog", { name: /Import 2 rows/ })
      .getByRole("button", { name: "Apply" })
      .click();
    await expect(page.getByText("2 rows were added.")).toBeVisible();
    expect(
      await sql(database, "SELECT full_name, note FROM public.imp_people ORDER BY id"),
    ).toEqual([
      { full_name: "Ann", note: "" },
      { full_name: "Bo", note: "x" },
    ]);
  });

  test("refuses a file in another encoding, a ragged row and an unclosed quote, naming the row", async ({
    page,
  }) => {
    const dialog = dialogOf(page);
    const input = dialog.getByLabel("CSV file");
    await input.setInputFiles(file(Buffer.from("name,city\nAnn,Zürich\n", "latin1")));
    await expect(dialog.getByRole("alert")).toContainText("not UTF-8 text");
    await expect(dialog.getByRole("button", { name: "Preview the import" })).toBeDisabled();

    await input.setInputFiles(file("a,b\n1,2\n3\n"));
    await expect(dialog.getByRole("alert")).toContainText("(row 3)");
    await expect(dialog.getByRole("alert")).toContainText("different number of values");

    await input.setInputFiles(file('a,b\n1,"never closed\n3,4\n'));
    await expect(dialog.getByRole("alert")).toContainText("never closed");
    await expect(dialog.getByRole("alert")).toContainText("(row 2)");

    await input.setInputFiles(file(""));
    await expect(dialog.getByRole("alert")).toContainText("empty");
    await expect(dialog.getByRole("button", { name: "Validate the file" })).toBeDisabled();
  });

  test("says which columns the table needs, and will not preview until they are chosen", async ({
    page,
  }) => {
    const dialog = dialogOf(page);
    await dialog.getByLabel("CSV file").setInputFiles(file("Email,Qty\na@x.test,1\n"));
    await expect(dialog.getByText(/full_name needs a value/)).toBeVisible();
    await expect(dialog.getByRole("button", { name: "Preview the import" })).toBeDisabled();
    await dialog.getByLabel(/for file column 2, Qty/).selectOption("full_name");
    await expect(dialog.getByRole("button", { name: "Preview the import" })).toBeEnabled();
    // Two columns of the file for one column of the table is not allowed.
    await dialog.getByLabel(/for file column 1, Email/).selectOption("full_name");
    await expect(dialog.getByText(/same column of the table/)).toBeVisible();
    await expect(dialog.getByRole("button", { name: "Preview the import" })).toBeDisabled();
  });

  test("the database checks the whole file, names the rows of the file, and applying a bad file adds nothing", async ({
    page,
    database,
  }) => {
    const dialog = dialogOf(page);
    const text =
      "Full Name,Email,Qty\n" +
      "Ann,ann@x.test,1\n" + // row 2
      "Bo,bo@x.test,-4\n" + // row 3: breaks the check
      "Cy,cy@x.test,3\n" +
      "Di,ann@x.test,4\n"; // row 5: the email of row 2
    await dialog.getByLabel("CSV file").setInputFiles(file(text));
    await dialog.getByRole("button", { name: "Validate the file" }).click();
    const report = dialog.getByRole("status", { name: "Check of the values" });
    await expect(report).toContainText("Problems found");
    await expect(report).toContainText("qty_not_negative");
    await expect(report).toContainText("Row 3");
    await expect(report).toContainText("Rows 2, 5");
    await expect(dialog.getByText(/Row numbers are the file's rows/)).toBeVisible();

    // Applying it anyway adds nothing: all or nothing.
    await dialog.getByRole("button", { name: "Preview the import" }).click();
    const preview = page.getByRole("dialog", { name: /Import 4 rows/ });
    await preview.getByRole("button", { name: "Apply" }).click();
    await expect(preview.getByRole("alert")).toContainText("The change was not applied");
    expect(await sql(database, "SELECT count(*)::int AS n FROM public.imp_people")).toEqual([
      { n: 0 },
    ]);
  });

  test("imports 100,000 rows, the most one import takes, in one transaction", async ({
    page,
    database,
  }) => {
    test.setTimeout(240_000);
    const dialog = dialogOf(page);
    // Past 10 MB on purpose: Next.js keeps only the first 10 MB of a body for its proxy unless the config says more.
    const body = Array.from(
      { length: 100_000 },
      (_, i) =>
        `Person ${i + 1},p${i + 1}@x.test,${i % 40},"a note, number ${i + 1} ${"x".repeat(90)}"`,
    ).join("\n");
    await dialog.getByLabel("CSV file").setInputFiles(file(`Full Name,Email,Qty,Note\n${body}\n`));
    await expect(dialog.getByRole("status").first()).toContainText("100,000 rows");
    await dialog.getByRole("button", { name: "Validate the file" }).click();
    await expect(dialog.getByRole("status", { name: "Check of the values" })).toContainText(
      "No problems found in 100,000 rows",
      { timeout: 120_000 },
    );
    await dialog.getByRole("button", { name: "Preview the import" }).click();
    const preview = page.getByRole("dialog", { name: /Import 100,000 rows/ });
    await expect(preview.getByText(/200 batches/).first()).toBeVisible({ timeout: 60_000 });
    await preview.getByRole("button", { name: "Apply" }).click();
    await expect(page.getByText("100,000 rows were added.")).toBeVisible({ timeout: 120_000 });
    expect(await sql(database, "SELECT count(*)::int AS n FROM public.imp_people")).toEqual([
      { n: 100_000 },
    ]);
  });

  test("passes axe in light, in dark and on a phone", async ({ page }) => {
    const dialog = dialogOf(page);
    await dialog
      .getByLabel("CSV file")
      .setInputFiles(file("Full Name,Email,Qty,Note\nAnn,a@x.test,1,x\nBo,b@x.test,2,y\n"));
    await dialog.getByRole("button", { name: "Validate the file" }).click();
    await expect(dialog.getByRole("status", { name: "Check of the values" })).toContainText(
      "No problems",
    );
    await axeInDialog(page, "the import (light)");
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: /^Theme:/ }).click();
    await page.getByRole("menuitemradio", { name: "Dark" }).click();
    await expect(page.getByRole("menu")).toHaveCount(0);
    await page.getByRole("button", { name: "Import CSV" }).click();
    await dialogOf(page)
      .getByLabel("CSV file")
      .setInputFiles(file("Full Name,Email,Qty,Note\nAnn,a@x.test,1,x\n"));
    await expect(
      dialogOf(page).getByRole("table", { name: "The first rows of the import" }),
    ).toBeVisible();
    await axeInDialog(page, "the import (dark)");
    await page.setViewportSize({ width: 390, height: 800 });
    await expect(dialogOf(page)).toBeVisible();
    await axeInDialog(page, "the import (phone)");
  });
});
