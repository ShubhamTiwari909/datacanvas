/**
 * The planner against a real PostgreSQL (`docs/migration-studio-plan.md`, section 7, milestone M1).
 * For each scenario two states are made, the planner writes the migration, and the oracle checks it:
 * applied to the first database it must give a structure with NO difference from the second, and its
 * rollback must give back the first. Rows are present where a step meets data.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. One pair of databases serves the whole file, each
 * scenario in a schema of its own.
 */
import type { MigrationPlan, MigrationStep, StepKind } from "@datacanvas/database-core";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
  createPair,
  disposePair,
  runPlanScenario,
  type Pair,
  type PlanScenario,
} from "./testing/round-trip.js";
import { testDatabaseUrl } from "./testing/index.js";

let pair: Pair;

/** A scenario that must work in both directions; returns the plan for further checks. */
async function works(scenario: PlanScenario): Promise<MigrationPlan> {
  const result = await runPlanScenario(pair, scenario);
  expect(result.upError, "the migration ran").toBeNull();
  expect(result.upDifferences, "nothing differs from the target").toEqual([]);
  expect(result.downError, "the rollback ran").toBeNull();
  expect(result.downDifferences, "the rollback restores the start").toEqual([]);
  return result.plan;
}

const kinds = (plan: MigrationPlan): StepKind[] => plan.steps.map((s) => s.kind);
const step = (plan: MigrationPlan, kind: StepKind): MigrationStep => {
  const found = plan.steps.find((s) => s.kind === kind);
  if (!found) throw new Error(`no ${kind} step in ${kinds(plan).join(", ")}`);
  return found;
};
const base = (body: string) => `CREATE SCHEMA {s}; ${body}`;

