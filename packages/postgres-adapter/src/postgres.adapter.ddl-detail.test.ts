/**
 * The parts of a definition that a migration must say (`docs/migration-studio-plan.md`,
 * section 6), read from a real PostgreSQL: identity, generated and collation of a column;
 * deferrable, not-yet-validated and match type of a constraint; partitioning, inheritance,
 * unlogged and storage options of a table; and the comments the structure did not carry.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway database.
 */
import type { DdlDetail } from "@datacanvas/database-core";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PostgresAdapter } from "./postgres.adapter.js";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

const SETUP = `
  CREATE SCHEMA app;
  COMMENT ON SCHEMA app IS 'the app';
  CREATE TABLE app.base (
    id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    label text COLLATE "C",
    total numeric,
    doubled numeric GENERATED ALWAYS AS (total * 2) STORED,
    by_default int GENERATED BY DEFAULT AS IDENTITY,
    plain text
  );
  CREATE TABLE app.child (id int PRIMARY KEY, base_id int);
  ALTER TABLE app.child ADD CONSTRAINT child_base_fk FOREIGN KEY (base_id) REFERENCES app.base (id)
    MATCH FULL DEFERRABLE INITIALLY DEFERRED;
  ALTER TABLE app.child ADD CONSTRAINT child_positive CHECK (id > 0) NOT VALID;
  ALTER TABLE app.child ADD CONSTRAINT child_plain CHECK (id < 1000000);
  ALTER TABLE app.child ADD CONSTRAINT child_loose FOREIGN KEY (base_id) REFERENCES app.base (id);
  CREATE UNLOGGED TABLE app.scratch (a int) WITH (fillfactor = 70);
  CREATE TABLE app.events (at date NOT NULL, v int) PARTITION BY RANGE (at);
  CREATE TABLE app.events_2026 PARTITION OF app.events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
  CREATE TABLE app.parent_a (x int);
  CREATE TABLE app.parent_b (y int);
  CREATE TABLE app.kid (z int) INHERITS (app.parent_a, app.parent_b);
  CREATE INDEX base_label_idx ON app.base (label);
  COMMENT ON INDEX app.base_label_idx IS 'find by label';
  COMMENT ON CONSTRAINT child_positive ON app.child IS 'positive ids';
  CREATE TYPE app.mood AS ENUM ('calm', 'angry');
  COMMENT ON TYPE app.mood IS 'moods';
  CREATE SEQUENCE app.counter;
  COMMENT ON SEQUENCE app.counter IS 'a counter';
  CREATE TABLE app.quiet (id int PRIMARY KEY, name text);
`;

describe.skipIf(!testDatabaseUrl())("the definition detail a migration needs", () => {
  let db: TestDatabase;
  let adapter: PostgresAdapter;
  let ddl: DdlDetail;

  beforeAll(async () => {
    db = await createTestDatabase();
    const { host, port, username, password } = db.connection;
    const client = new pg.Client({ host, port, user: username, password, database: db.dbName });
    await client.connect();
    try {
      await client.query(SETUP);
    } finally {
      await client.end();
    }
    adapter = new PostgresAdapter(db.connection);
    await adapter.connect();
    const tables = (await adapter.getTables("app")).map((t) => ({ schema: "app", name: t.name }));
    ddl = await adapter.getDdlDetail(tables, ["app"]);
  }, 60_000);

  afterAll(async () => {
    await adapter?.disconnect();
    await db?.dispose();
  });

  it("reads the server version", () => {
    expect(ddl.serverVersion).toBeGreaterThanOrEqual(120000);
    expect(ddl.serverVersion).toBeLessThan(400000);
  });

  it("lists only the columns that are identity, generated or have their own collation", () => {
    expect(ddl.columns).toEqual([
      {
        schema: "app",
        table: "base",
        column: "by_default",
        identity: "by_default",
        generated: null,
        collation: null,
        collationSchema: null,
      },
      {
        schema: "app",
        table: "base",
        column: "doubled",
        identity: null,
        generated: "stored",
        collation: null,
        collationSchema: null,
      },
      {
        schema: "app",
        table: "base",
        column: "id",
        identity: "always",
        generated: null,
        collation: null,
        collationSchema: null,
      },
      {
        schema: "app",
        table: "base",
        column: "label",
        identity: null,
        generated: null,
        collation: "C",
        collationSchema: "pg_catalog",
      },
    ]);
  });

  it("lists only the constraints that are deferrable, not validated or have a match type", () => {
    expect(ddl.constraints).toEqual([
      {
        schema: "app",
        table: "child",
        name: "child_base_fk",
        deferrable: true,
        initiallyDeferred: true,
        validated: true,
        match: "full",
      },
      {
        schema: "app",
        table: "child",
        name: "child_positive",
        deferrable: false,
        initiallyDeferred: false,
        validated: false,
        match: null,
      },
    ]);
  });

  it("lists only the tables that are partitioned, partitions, inherit, are unlogged or have options", () => {
    const by = Object.fromEntries(ddl.tables.map((t) => [t.name, t]));
    expect(Object.keys(by).sort()).toEqual(["events", "events_2026", "kid", "scratch"]);
    expect(by.scratch).toMatchObject({
      unlogged: true,
      options: ["fillfactor=70"],
      partitionKey: null,
    });
    expect(by.events).toMatchObject({
      partitionKey: "RANGE (at)",
      partitionOf: null,
      unlogged: false,
    });
    expect(by.events_2026).toMatchObject({
      partitionOf: {
        schema: "app",
        table: "events",
        bound: "FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')",
      },
      inherits: [],
    });
    expect(by.kid).toMatchObject({
      inherits: [
        { schema: "app", table: "parent_a" },
        { schema: "app", table: "parent_b" },
      ],
      partitionOf: null,
    });
  });

  it("reads the comments the structure did not carry", () => {
    expect(ddl.comments).toEqual([
      {
        target: "constraint",
        schema: "app",
        table: "child",
        name: "child_positive",
        comment: "positive ids",
      },
      {
        target: "index",
        schema: "app",
        table: "base",
        name: "base_label_idx",
        comment: "find by label",
      },
      { target: "schema", schema: "app", table: null, name: "app", comment: "the app" },
      { target: "sequence", schema: "app", table: null, name: "counter", comment: "a counter" },
      { target: "type", schema: "app", table: null, name: "mood", comment: "moods" },
    ]);
  });

  it("says nothing about a table with nothing special, or one that was not asked for", async () => {
    const only = await adapter.getDdlDetail([{ schema: "app", name: "quiet" }], ["app"]);
    expect(only.columns).toEqual([]);
    expect(only.constraints).toEqual([]);
    expect(only.tables).toEqual([]);
    // The schema, type and sequence comments belong to the schema, not to a table.
    expect(only.comments.map((c) => c.target).sort()).toEqual(["schema", "sequence", "type"]);
  });

  it("is the same twice, and does not need the tables to be listed in any order", async () => {
    const tables = (await adapter.getTables("app")).map((t) => ({ schema: "app", name: t.name }));
    const again = await adapter.getDdlDetail([...tables].reverse(), ["app"]);
    expect(again).toEqual(ddl);
  });

  it("reads nothing for a database with no tables listed", async () => {
    const none = await adapter.getDdlDetail([], []);
    expect(none.columns).toEqual([]);
    expect(none.comments).toEqual([]);
    expect(none.serverVersion).toBe(ddl.serverVersion);
  });
});
