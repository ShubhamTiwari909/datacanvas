/**
 * The INSERT script of an export against a real PostgreSQL (1.10.0, V5; decision 167): a table with every kind of
 * value is exported, emptied, and the script is run; the rows must be back, cell by cell. This is the reason the format
 * was left out until now ("another thing to quote correctly"): the quoting is proved by round trip, not by reading it.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway database.
 */
import {
  createFormatter,
  type ExportEvent,
  type ExportRowsOptions,
  type TableRef,
} from "@datacanvas/database-core";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PostgresAdapter } from "./postgres.adapter.js";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

const SQL = `
  CREATE TYPE mood AS ENUM ('sad', 'ok', 'it''s "fine"');
  CREATE TABLE rt_src (
    id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    n bigint, price numeric(12,3), flag boolean, born date, seen timestamptz, span interval,
    note text, big text, doc jsonb, plain json, raw bytea, uid uuid, tags text[], nums int[],
    feel mood, addr inet, fixed char(5),
    doubled int GENERATED ALWAYS AS (n * 2) STORED
  );
  INSERT INTO rt_src (n, price, flag, born, seen, span, note, big, doc, plain, raw, uid, tags, nums, feel, addr, fixed) VALUES
    (1, 12.5, true, '2026-11-24', '2026-11-24 10:00:00+05:30', '1 day 02:03:04', 'plain', 'x', '{"a": [1, 2, {"b": null}]}', '{"k":  "v"}', '\\x00ff10', 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11', ARRAY['a','b c'], ARRAY[1,2,3], 'ok', '10.0.0.1', 'ab'),
    (2, NULL, NULL, NULL, NULL, NULL, '', NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL),
    (3, -7, false, '1999-12-31', 'infinity', '-1 month', E'quote '' double " backslash \\\\ newline \\n tab \\t cr \\r semicolon ; dash -- end', repeat('é€😀', 100), '[]', '1', '\\x', NULL, ARRAY['it''s', '"q"', 'a,b', NULL], '{}', 'it''s "fine"', '::1', 'a''b"c'),
    (4, 0, true, NULL, NULL, NULL, 'Robert''); DROP TABLE rt_src;--', NULL, '{"s": "\\u00e9x"}', NULL, NULL, NULL, NULL, NULL, 'sad', NULL, NULL),
    (5, 1, NULL, NULL, NULL, NULL, E'}\\nTable x {', NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL);
  CREATE TABLE rt_only (password text DEFAULT 'kept-by-default');
  INSERT INTO rt_only VALUES ('hunter2'), ('hunter3');
  CREATE TABLE "rt ""odd""
name" ("co""l" int PRIMARY KEY, "t""x" text);
  INSERT INTO "rt ""odd""
name" VALUES (1, 'a'), (2, 'b');
`;

describe.skipIf(!testDatabaseUrl())("the INSERT script round trip", () => {
  let db: TestDatabase;
  let sql: pg.Client;
  let adapter: PostgresAdapter;

  beforeAll(async () => {
    db = await createTestDatabase();
    const { host, port, username, password } = db.connection;
    sql = new pg.Client({ host, port, user: username, password, database: db.dbName });
    await sql.connect();
    await sql.query(SQL);
    adapter = new PostgresAdapter(db.connection);
    await adapter.connect();
  }, 60_000);
  afterAll(async () => {
    await adapter?.disconnect();
    await sql?.end().catch(() => {});
    await db?.dispose().catch(() => {});
  });

  /** The script for a table, as the server writes it: the formatter's start, rows and end for the events of the reader. */
  async function script(
    table: TableRef,
    options: Partial<ExportRowsOptions> = {},
  ): Promise<string> {
    const formatter = createFormatter(
      { format: "sql", delimiter: ",", header: true, nullText: "", meta: false },
      { table, at: new Date("2026-11-24T00:00:00Z"), filters: [] },
    );
    let text = "";
    let leftOut: string[] = [];
    let rows = 0;
    await adapter.exportRows(table, { revealColumns: [], ...options }, (event: ExportEvent) => {
      if (event.kind === "start") {
        leftOut = event.leftOut;
        text += formatter.start(event.columns, leftOut);
      } else if (event.kind === "rows") {
        rows += event.rows.length;
        text += formatter.rows(event.rows);
      } else {
        text += formatter.end({ ...event, rows, leftOut });
      }
      return undefined;
    });
    return text;
  }

  const asText = async (name: string, columns = "*"): Promise<string[]> =>
    (
      await sql.query(`SELECT t::text AS r FROM (SELECT ${columns} FROM ${name}) t ORDER BY 1`)
    ).rows.map((r) => r.r as string);

  it("brings every row back, cell by cell: every type, NULLs, quotes, backslashes, line breaks, unicode, identity always", async () => {
    const before = await asText("rt_src");
    const text = await script({ schema: "public", name: "rt_src" });
    expect(text).toContain("OVERRIDING SYSTEM VALUE");
    expect(text.trimEnd().endsWith("COMMIT;")).toBe(true);
    // The generated column is left out of the script and says so.
    expect(text).toContain("-- Left out because they are generated by the database: doubled.");
    expect(text).not.toMatch(/"doubled"/);
    await sql.query("TRUNCATE rt_src");
    await sql.query(text);
    // The generated column is computed again, so the whole row, generated column included, is the same.
    expect(await asText("rt_src")).toEqual(before);
    expect(before).toHaveLength(5);
    // The hostile values did nothing: the table is still there.
    expect((await sql.query("SELECT count(*)::int AS n FROM rt_src")).rows[0]).toEqual({ n: 5 });
  });

  it("writes DEFAULT VALUES for each row of a table whose every column was left out (a hidden column)", async () => {
    const text = await script({ schema: "public", name: "rt_only" });
    expect(text).toContain('INSERT INTO "public"."rt_only" DEFAULT VALUES;');
    expect(text).toContain("-- Left out because they look sensitive: password.");
    expect(text).not.toContain("hunter");
    await sql.query("TRUNCATE rt_only");
    await sql.query(text);
    expect((await sql.query("SELECT password FROM rt_only")).rows).toEqual([
      { password: "kept-by-default" },
      { password: "kept-by-default" },
    ]);
  });

  it("quotes a table and a column named with quotes and a line break", async () => {
    const table = { schema: "public", name: 'rt "odd"\nname' };
    const text = await script(table);
    expect(text).toContain('INSERT INTO "public"."rt ""odd""\nname" ("co""l", "t""x") VALUES');
    // The comment lines flatten the name: no line of the file starts with anything but a statement or a comment.
    for (const line of text.split("\n")) {
      expect(
        line === "" || /^(--|SET |BEGIN;|COMMIT;|ROLLBACK;|INSERT |  \(|name")/.test(line),
        line,
      ).toBe(true);
    }
    await sql.query('TRUNCATE "rt ""odd""\nname"');
    await sql.query(text);
    expect((await sql.query('SELECT count(*)::int AS n FROM "rt ""odd""\nname"')).rows[0]).toEqual({
      n: 2,
    });
  });
});
