/**
 * The statistics of a table against a real PostgreSQL (1.10.0, V3; decision 165): the share of NULLs, the distinct
 * values, the width, the sizes and the upkeep times, from the server's own statistics. **No row and no value is read:**
 * the marker values of the table must not be anywhere in the answer, whatever the table holds.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway database.
 */
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PostgresAdapter } from "./postgres.adapter.js";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

const SQL = `
  CREATE TABLE st_people (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL, qty int, note text, password_hash text
  );
  INSERT INTO st_people (email, qty, note, password_hash)
  SELECT 'MARKER-EMAIL-' || i, i % 10, CASE WHEN i % 2 = 0 THEN 'MARKER-NOTE-' || (i % 3) END, 'MARKER-SECRET-' || i
  FROM generate_series(1, 2000) i;
  ANALYZE st_people;
  CREATE TABLE st_fresh (id int PRIMARY KEY, v text) WITH (autovacuum_enabled = false);
  INSERT INTO st_fresh SELECT i, 'MARKER-FRESH-' || i FROM generate_series(1, 500) i;
  CREATE VIEW st_view AS SELECT id FROM st_people;
  CREATE MATERIALIZED VIEW st_mat AS SELECT id, qty FROM st_people;
  ANALYZE st_mat;
  CREATE TABLE st_part (id int, region text) PARTITION BY LIST (region);
  CREATE TABLE st_part_eu PARTITION OF st_part FOR VALUES IN ('eu');
`;

describe.skipIf(!testDatabaseUrl())("PostgresAdapter table statistics", () => {
  let db: TestDatabase;
  let adapter: PostgresAdapter;
  let sql: pg.Client;
  const ask = (name: string) => adapter.getTableStatistics({ schema: "public", name });

  beforeAll(async () => {
    db = await createTestDatabase();
    const { host, port, username, password } = db.connection;
    sql = new pg.Client({ host, port, user: username, password, database: db.dbName });
    await sql.connect();
    await sql.query(SQL);
    adapter = new PostgresAdapter(db.connection);
    await adapter.connect();
  }, 60_000);
  afterAll(async () => {
    await adapter?.disconnect();
    await sql?.end().catch(() => {});
    await db?.dispose().catch(() => {});
  });

  it("gives the share of NULLs, the distinct values, the width and the order of each column of an analysed table", async () => {
    const stats = (await ask("st_people"))!;
    expect(stats.kind).toBe("table");
    expect(stats.columns.map((c) => c.column)).toEqual([
      "id",
      "email",
      "qty",
      "note",
      "password_hash",
    ]);
    const by = (name: string) => stats.columns.find((c) => c.column === name)!;
    expect(by("note").nullFraction).toBeCloseTo(0.5, 1);
    expect(by("id").nullFraction).toBe(0);
    // A column whose values all differ: a share (every row), not a count.
    expect(by("email").distinctShare).toBe(1);
    expect(by("email").distinctValues).toBeNull();
    // A column with ten values: a count.
    expect(by("qty").distinctValues).toBe(10);
    expect(by("qty").distinctShare).toBeNull();
    expect(by("email").averageWidth).toBeGreaterThan(10);
    expect(by("id").correlation).toBeCloseTo(1, 1);
    expect(stats.columns.every((c) => c.hasStatistics)).toBe(true);
  });

  it("gives the sizes, the estimate and the times of the last analyze", async () => {
    // Before PostgreSQL 15 the time of an ANALYZE reaches pg_stat_all_tables through the statistics collector, about a
    // half second after it ran: wait for it (PostgreSQL 13 in CI showed it as null straight after).
    let stats = (await ask("st_people"))!;
    for (let i = 0; i < 40 && stats.lastAnalyze === null; i++) {
      await new Promise((resolve) => setTimeout(resolve, 250));
      stats = (await ask("st_people"))!;
    }
    expect(stats.estimatedRows).toBe(2000);
    expect(stats.tableBytes).toBeGreaterThan(0);
    expect(stats.indexBytes).toBeGreaterThan(0);
    expect(stats.toastBytes).toBeGreaterThanOrEqual(0);
    expect(stats.deadRows ?? 0).toBe(0);
    // ANALYZE was run by hand: that is the last analyze, as a time.
    expect(stats.lastAnalyze).toMatch(/^\d{4}-\d{2}-\d{2}T/);
  });

  it("reads no row and no value: not one marker of the table is anywhere in the answer", async () => {
    for (const name of ["st_people", "st_fresh", "st_mat"]) {
      const text = JSON.stringify(await ask(name));
      expect(text, name).not.toContain("MARKER");
    }
  });

  it("says that a table that was never analysed has no figures, not zeros", async () => {
    const stats = (await ask("st_fresh"))!;
    expect(stats.columns.every((c) => !c.hasStatistics)).toBe(true);
    for (const c of stats.columns) {
      expect([
        c.nullFraction,
        c.distinctValues,
        c.distinctShare,
        c.averageWidth,
        c.correlation,
      ]).toEqual([null, null, null, null, null]);
    }
    expect(stats.estimatedRows).toBeNull();
    expect(stats.lastAnalyze).toBeNull();
    expect(stats.lastAutoanalyze).toBeNull();
    // It does have a size.
    expect(stats.tableBytes).toBeGreaterThan(0);
  });

  it("reads a materialized view and a partitioned table, and is null for a view and for a name that is nothing", async () => {
    expect((await ask("st_mat"))!.kind).toBe("materialized");
    expect((await ask("st_part"))!.kind).toBe("partitioned");
    expect(await ask("st_view")).toBeNull();
    expect(await ask("no_such_table")).toBeNull();
    expect(
      await adapter.getTableStatistics({ schema: "no_such_schema", name: "st_people" }),
    ).toBeNull();
  });

  it("takes a name that looks like SQL as a name", async () => {
    expect(await ask('st_people"; SELECT 1; --')).toBeNull();
    expect(await ask("st_people' OR '1'='1")).toBeNull();
  });
});
