/**
 * `validateRows()` with `listAll` against a real PostgreSQL (`docs/write-side-v2-plan.md`, sections 4.3 and
 * 13.3): an import that may leave out its failing rows must be told EVERY one, up to
 * `VALIDATE_LIST_ALL_MAX_FAILURES`. Each rule lists more than the usual twenty rows; more failing rows than the
 * limit is `stopped_early`; the report still holds no value; and without `listAll` nothing changes.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway database.
 */
import {
  VALIDATE_LIST_ALL_MAX_FAILURES,
  VALIDATE_ROWS_LISTED,
  type ValidateRequest,
  type ValidationReport,
} from "@datacanvas/database-core";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PostgresAdapter } from "./postgres.adapter.js";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

const SECRET = "hunter2-SECRET-VALUE";
/** Rows already in `wide`, so that a key value can collide with one. */
const EXISTING = 1200;

const SQL = `
  CREATE TABLE tag_parent (tag text PRIMARY KEY);
  INSERT INTO tag_parent VALUES ('ok');
  CREATE TABLE wide (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    price numeric CONSTRAINT wide_price_ok CHECK (price >= 0),
    email text CONSTRAINT wide_email_key UNIQUE,
    tag text CONSTRAINT wide_tag_fkey REFERENCES tag_parent (tag)
  );
  INSERT INTO wide (id, name, price, email)
    SELECT g, 'n', 0, 'e' || g FROM generate_series(1, ${EXISTING}) AS g;

  -- every column text, so that every cell of a request can hold the marker
  CREATE TABLE marked_parent (ref text PRIMARY KEY);
  INSERT INTO marked_parent VALUES ('${SECRET}-ref-ok');
  CREATE TABLE marked (
    name text NOT NULL CONSTRAINT marked_name_short CHECK (length(name) < 40),
    code varchar(30),
    email text CONSTRAINT marked_email_key UNIQUE,
    ref text CONSTRAINT marked_ref_fkey REFERENCES marked_parent (ref)
  );
  INSERT INTO marked VALUES ('${SECRET}-x', NULL, '${SECRET}-taken', NULL);
`;

/** 1-based row numbers `from` to `to`. */
const range = (from: number, to: number) =>
  Array.from({ length: to - from + 1 }, (_, i) => from + i);

/** Every row number some issue names. */
const named = (report: ValidationReport) => new Set(report.issues.flatMap((i) => i.rows));

describe.skipIf(!testDatabaseUrl())("PostgreSQL validateRows with listAll", () => {
  let db: TestDatabase;
  let client: pg.Client;
  let adapter: PostgresAdapter;
  const t = (name: string) => ({ schema: "public", name });

  beforeAll(async () => {
    db = await createTestDatabase();
    const { host, port, username, password } = db.connection;
    client = new pg.Client({ host, port, user: username, password, database: db.dbName });
    await client.connect();
    await client.query(SQL);
    adapter = new PostgresAdapter(db.connection);
    await adapter.connect();
  }, 120_000);
  afterAll(async () => {
    await adapter?.disconnect();
    await client?.end().catch(() => {});
    await db?.dispose().catch(() => {});
  });

  const insert = (
    table: string,
    columns: string[],
    rows: Array<Array<string | null>>,
    listAll?: boolean,
  ): ValidateRequest => ({
    table: t(table),
    mode: "insert",
    columns,
    rows,
    ...(listAll === undefined ? {} : { listAll }),
  });

  const COLUMNS = ["name", "price", "email", "tag"];
  /** A row of `wide` that breaks nothing (the `n`th of the request). */
  const fine = (n: number): Array<string | null> => [`n${n}`, "1", `fresh${n}@x.test`, "ok"];
  /** A file breaking each rule on 25 rows, in this order, then 50 rows that pass. */
  const PER_RULE = 25;
  const mixed = (): Array<Array<string | null>> =>
    Array.from({ length: 6 * PER_RULE + 50 }, (_, i) => {
      const n = i + 1;
      const row = fine(n);
      switch (Math.floor(i / PER_RULE)) {
        case 0:
          row[0] = null; // not_null
          break;
        case 1:
          row[1] = "-1"; // check
          break;
        case 2:
          row[1] = "abc"; // type
          break;
        case 3:
          row[2] = "dup@x.test"; // unique_in_request
          break;
        case 4:
          row[2] = `e${n}`; // unique_existing (a row of the table holds it)
          break;
        case 5:
          row[3] = "missing"; // foreign_key
          break;
      }
      return row;
    });
  const block = (k: number) => range(k * PER_RULE + 1, (k + 1) * PER_RULE);

  it("lists every failing row of each rule, past the usual twenty, and names every failing row", async () => {
    expect(PER_RULE).toBeGreaterThan(VALIDATE_ROWS_LISTED);
    const report = await adapter.validateRows(insert("wide", COLUMNS, mixed(), true));
    expect(report.rows).toBe(6 * PER_RULE + 50);
    expect(report.passed).toBe(50);
    expect(report.notChecked).not.toContain("stopped_early");
    const one = (rule: string) => report.issues.filter((i) => i.rule === rule);
    expect(one("not_null")).toEqual([
      { rule: "not_null", column: "name", constraint: null, count: PER_RULE, rows: block(0) },
    ]);
    expect(one("check")).toEqual([
      { rule: "check", column: null, constraint: "wide_price_ok", count: PER_RULE, rows: block(1) },
    ]);
    expect(one("type")).toEqual([
      { rule: "type", column: "price", constraint: null, count: PER_RULE, rows: block(2) },
    ]);
    expect(one("unique_in_request")).toEqual([
      {
        rule: "unique_in_request",
        column: null,
        constraint: "wide_email_key",
        count: PER_RULE,
        rows: block(3),
      },
    ]);
    expect(one("unique_existing")).toEqual([
      {
        rule: "unique_existing",
        column: null,
        constraint: "wide_email_key",
        count: PER_RULE,
        rows: block(4),
      },
    ]);
    expect(one("foreign_key")).toEqual([
      {
        rule: "foreign_key",
        column: null,
        constraint: "wide_tag_fkey",
        count: PER_RULE,
        rows: block(5),
      },
    ]);
    expect(report.issues).toHaveLength(6);
    // The rows the browser leaves out: every failing row, and none that passed.
    expect([...named(report)].sort((a, b) => a - b)).toEqual(range(1, 6 * PER_RULE));
  }, 60_000);

  it("without listAll, the same file gives the usual report: twenty rows a rule, every row counted", async () => {
    const report = await adapter.validateRows(insert("wide", COLUMNS, mixed()));
    expect(report.issues).toHaveLength(6);
    for (const issue of report.issues) {
      expect(issue.count).toBe(PER_RULE);
      expect(issue.rows).toHaveLength(VALIDATE_ROWS_LISTED);
    }
    expect(report.issues.map((i) => i.rows[0])).toEqual([0, 1, 2, 3, 4, 5].map((k) => k * 25 + 1));
    // Rows counted by a query without being named still count as failed.
    expect(report.passed).toBe(50);
    expect(report.notChecked).not.toContain("stopped_early");
    // And `listAll: false` is the same as leaving it out.
    expect(await adapter.validateRows(insert("wide", COLUMNS, mixed(), false))).toEqual(report);
  }, 60_000);

  it("without listAll, still stops looking after a hundred failing rows", async () => {
    const rows = Array.from({ length: 300 }, (_, i) => [`n${i}`, "-1", null, null]);
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows));
    expect(report.issues[0]!.rows).toHaveLength(VALIDATE_ROWS_LISTED);
    expect(report.issues[0]!.count).toBe(100);
    expect(report.notChecked).toContain("stopped_early");
  }, 60_000);

  it("finds failing rows spread across a file, each one", async () => {
    const total = 3000;
    const bad = new Set(Array.from({ length: 300 }, (_, k) => k * 10 + (k % 7)));
    const rows = Array.from({ length: total }, (_, i) => [
      `n${i}`,
      bad.has(i) ? "-1" : "1",
      null,
      null,
    ]);
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows, true));
    expect(report.notChecked).not.toContain("stopped_early");
    expect(report.passed).toBe(total - bad.size);
    expect(report.issues).toEqual([
      {
        rule: "check",
        column: null,
        constraint: "wide_price_ok",
        count: bad.size,
        rows: [...bad].map((i) => i + 1).sort((a, b) => a - b),
      },
    ]);
  }, 60_000);

  it("lists exactly the limit without stopping early", async () => {
    const total = 1500;
    const rows = Array.from({ length: total }, (_, i) => [
      `n${i}`,
      i < VALIDATE_LIST_ALL_MAX_FAILURES ? "-1" : "1",
      null,
      null,
    ]);
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows, true));
    expect(report.notChecked).not.toContain("stopped_early");
    expect(report.passed).toBe(total - VALIDATE_LIST_ALL_MAX_FAILURES);
    expect(report.issues).toHaveLength(1);
    expect(report.issues[0]!.count).toBe(VALIDATE_LIST_ALL_MAX_FAILURES);
    expect(report.issues[0]!.rows).toEqual(range(1, VALIDATE_LIST_ALL_MAX_FAILURES));
  }, 60_000);

  it("says stopped_early when more rows fail than the limit: found by the copy", async () => {
    const total = 2000;
    const from = 500;
    const rows = Array.from({ length: total }, (_, i) => [
      `n${i}`,
      i >= from && i <= from + VALIDATE_LIST_ALL_MAX_FAILURES ? "-1" : "1",
      null,
      null,
    ]);
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows, true));
    expect(report.notChecked).toContain("stopped_early");
    const issue = report.issues[0]!;
    expect(issue.count).toBeGreaterThan(VALIDATE_LIST_ALL_MAX_FAILURES);
    expect(issue.rows).toHaveLength(VALIDATE_LIST_ALL_MAX_FAILURES);
  }, 60_000);

  it("says stopped_early when more rows fail than the limit: counted by a query", async () => {
    const over = VALIDATE_LIST_ALL_MAX_FAILURES + 1;
    expect(over).toBeLessThanOrEqual(EXISTING);
    const rows = Array.from({ length: over + 10 }, (_, i) => [
      `n${i}`,
      "1",
      i < over ? `e${i + 1}` : `fresh${i}`,
      null,
    ]);
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows, true));
    expect(report.notChecked).toContain("stopped_early");
    expect(report.issues).toEqual([
      {
        rule: "unique_existing",
        column: null,
        constraint: "wide_email_key",
        count: over,
        rows: range(1, VALIDATE_LIST_ALL_MAX_FAILURES),
      },
    ]);
  }, 60_000);

  it("says stopped_early when the rules together fail more rows than the limit", async () => {
    const half = 600;
    const rows = Array.from({ length: 2 * half }, (_, i) =>
      i < half ? [`n${i}`, "-1", null, null] : [`n${i}`, "1", null, "missing"],
    );
    const report = await adapter.validateRows(insert("wide", COLUMNS, rows, true));
    expect(report.issues.map((i) => [i.rule, i.count])).toEqual([
      ["check", half],
      ["foreign_key", half],
    ]);
    expect(report.notChecked).toContain("stopped_early");
  }, 60_000);

  it("never puts a value in the report, with a marker in every cell and every rule broken", async () => {
    const m = SECRET;
    const rows: Array<Array<string | null>> = [];
    for (let k = 0; k < 6; k++) {
      for (let j = 0; j < PER_RULE; j++) {
        const n = rows.length + 1;
        const row: Array<string | null> = [`${m}-${n}`, `${m}c`, `${m}-e${n}`, `${m}-ref-ok`];
        if (k === 0) row[0] = null; // not_null (the one cell without a value)
        if (k === 1) row[0] = `${m}-${"x".repeat(30)}`; // check: too long for the rule
        if (k === 2) row[1] = `${m}-${"y".repeat(20)}`; // type: too long for varchar(30)
        if (k === 3) row[2] = `${m}-dup`; // unique_in_request
        if (k === 4) row[2] = `${m}-taken`; // unique_existing (also repeated within the request)
        if (k === 5) row[3] = `${m}-ref-missing-${n}`; // foreign_key
        rows.push(row);
      }
    }
    const report = await adapter.validateRows(
      insert("marked", ["name", "code", "email", "ref"], rows, true),
    );
    expect(new Set(report.issues.map((i) => i.rule))).toEqual(
      new Set(["not_null", "check", "type", "unique_in_request", "unique_existing", "foreign_key"]),
    );
    expect([...named(report)].sort((a, b) => a - b)).toEqual(range(1, 6 * PER_RULE));
    const text = JSON.stringify(report);
    expect(text).not.toContain(SECRET);
    expect(text).not.toContain("hunter2");
    expect(text).not.toContain("SECRET");
  }, 60_000);

  it("is refused for an update, and when it is not a boolean", async () => {
    const code = async (request: unknown): Promise<string> => {
      try {
        await adapter.validateRows(request as ValidateRequest);
      } catch (error) {
        return (error as { code?: string }).code ?? "(no code)";
      }
      return "(no error)";
    };
    expect(
      await code({
        table: t("wide"),
        mode: "update",
        columns: ["name"],
        rows: [["x"]],
        key: [{ column: "id", value: "1" }],
        listAll: true,
      }),
    ).toBe("invalid_request");
    expect(await code({ ...insert("wide", ["name"], [["x"]]), listAll: "yes" })).toBe(
      "invalid_request",
    );
  });
});
