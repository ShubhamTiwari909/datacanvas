/**
 * Spike D0 of the advanced data workspace (`docs/advanced-data-workspace-plan.md`, section 6.2):
 * what a validation in a TEMPORARY TABLE can and cannot rely on. These are the facts the design
 * stands on, kept as tests so a PostgreSQL version that changes one is noticed.
 *
 *   1. `LIKE ... INCLUDING ...` copies types, domains, NOT NULL, CHECK, unique indexes, generated
 *      columns; it copies NO triggers and NO foreign keys.
 *   2. Copied DEFAULTS reach SEQUENCES, which a rollback does not undo: the real sequence advances.
 *      So defaults that call a sequence must be dropped from the copy.
 *   3. The error carries the SQLSTATE and, for some rules, the column or the constraint; for a
 *      value that does not cast it carries neither, so the column is found by casting the row's
 *      cells one by one.
 *   4. Rows that fail are found by splitting a batch in halves (savepoints), not one by one.
 *   5. Nothing is left behind, and a trigger on the real table never fires.
 */
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

let db: TestDatabase;
let client: pg.Client;

beforeAll(async () => {
  if (!testDatabaseUrl()) return;
  db = await createTestDatabase();
  const { host, port, username, password } = db.connection;
  client = new pg.Client({ host, port, user: username, password, database: db.dbName });
  await client.connect();
}, 120_000);
afterAll(async () => {
  await client?.end().catch(() => {});
  await db?.dispose().catch(() => {});
});

const q = (text: string, values: unknown[] = []) => client.query(text, values);

/**
 * The checking copy of the target: its types, domains, NOT NULL and CHECK rules, generated
 * columns; no indexes (uniqueness is asked in queries, so a key the database would generate
 * does not have to be supplied), and the NOT NULL of every column the database would fill by
 * itself (a default, an identity) relaxed, because the row is not asked for what it will not give.
 */
async function checkingCopy(): Promise<void> {
  await q("CREATE TEMP TABLE chk (LIKE v.target INCLUDING CONSTRAINTS INCLUDING GENERATED)");
  await q(
    "ALTER TABLE chk ALTER COLUMN id DROP NOT NULL, ALTER COLUMN made DROP NOT NULL, ALTER COLUMN serial_no DROP NOT NULL",
  );
}

/** Run `work` in a transaction that is always rolled back. */
async function rolledBack<T>(work: () => Promise<T>): Promise<T> {
  await q("BEGIN");
  try {
    return await work();
  } finally {
    await q("ROLLBACK");
  }
}

describe.skipIf(!testDatabaseUrl())("validation in a temporary table (spike D0)", () => {
  beforeAll(async () => {
    await q(`
      CREATE SCHEMA v;
      CREATE DOMAIN v.posint AS int CHECK (VALUE > 0);
      CREATE TABLE v.parent (id int PRIMARY KEY);
      INSERT INTO v.parent VALUES (1), (2);
      CREATE SEQUENCE v.target_seq;
      CREATE TABLE v.audit (n int);
      CREATE TABLE v.target (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        qty v.posint,
        email text UNIQUE,
        price numeric(8,2) CHECK (price >= 0),
        total numeric GENERATED ALWAYS AS (price * 2) STORED,
        parent_id int REFERENCES v.parent (id),
        made timestamptz NOT NULL DEFAULT now(),
        serial_no int NOT NULL DEFAULT nextval('v.target_seq')
      );
      CREATE FUNCTION v.note() RETURNS trigger LANGUAGE plpgsql AS $x$
        BEGIN INSERT INTO v.audit VALUES (1); RETURN NEW; END; $x$;
      CREATE TRIGGER target_note BEFORE INSERT ON v.target FOR EACH ROW EXECUTE FUNCTION v.note();
      INSERT INTO v.target (name, email) VALUES ('existing', 'taken@x.test');
    `);
  });

  it("copies the rules the database checks itself, and no triggers or foreign keys", async () => {
    await rolledBack(async () => {
      await q(
        "CREATE TEMP TABLE chk (LIKE v.target INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING GENERATED)",
      );
      const constraints = await q(
        `SELECT conname, contype FROM pg_constraint WHERE conrelid = 'pg_temp.chk'::regclass ORDER BY 1`,
      );
      const kinds = constraints.rows.map((r) => r.contype as string);
      expect(kinds).toContain("c"); // the price check
      expect(kinds).not.toContain("f"); // no foreign key
      const triggers = await q(
        `SELECT count(*)::int AS n FROM pg_trigger WHERE tgrelid = 'pg_temp.chk'::regclass AND NOT tgisinternal`,
      );
      expect(triggers.rows[0]!.n).toBe(0);
      const indexes = await q(
        `SELECT count(*)::int AS n FROM pg_index WHERE indrelid = 'pg_temp.chk'::regclass AND indisunique`,
      );
      expect(indexes.rows[0]!.n).toBeGreaterThanOrEqual(2); // the key and the unique email
      // The domain is still the column's type, so its check applies.
      await expect(
        q("INSERT INTO chk (name, qty, made, serial_no) VALUES ('a', 0, now(), 1)"),
      ).rejects.toMatchObject({
        code: "23514",
      });
    });
  });

  it("does not run a trigger of the real table, and leaves nothing behind", async () => {
    await rolledBack(async () => {
      await checkingCopy();
      await q("INSERT INTO chk (name) VALUES ('a')");
    });
    expect((await q("SELECT count(*)::int AS n FROM v.audit")).rows[0]!.n).toBe(1); // the one of the real insert in setup
    const gone = await q("SELECT to_regclass('pg_temp.chk') AS t");
    expect(gone.rows[0]!.t).toBeNull();
  });

  it("advances a real sequence through a copied default, which a rollback does not undo", async () => {
    const before = (await q("SELECT last_value::int AS n, is_called FROM v.target_seq")).rows[0]!;
    await rolledBack(async () => {
      await q("CREATE TEMP TABLE chk (LIKE v.target INCLUDING DEFAULTS INCLUDING GENERATED)");
      await q("INSERT INTO chk (id, name) VALUES (1, 'uses the default')");
    });
    const after = (await q("SELECT last_value::int AS n, is_called FROM v.target_seq")).rows[0]!;
    expect(after.n).toBeGreaterThan(before.n); // the finding: defaults must not be copied as they are
  });

  it("without the defaults, a column that had one is relaxed instead, and the sequence stays put", async () => {
    const before = (await q("SELECT last_value::int AS n FROM v.target_seq")).rows[0]!.n;
    await rolledBack(async () => {
      await checkingCopy();
      await q("INSERT INTO chk (name) VALUES ('no default used')");
    });
    const after = (await q("SELECT last_value::int AS n FROM v.target_seq")).rows[0]!.n;
    expect(after).toBe(before);
  });

  it("names the rule for some failures and not for a value that does not cast", async () => {
    await rolledBack(async () => {
      await checkingCopy();
      const fail = async (sql: string, values: unknown[]) => {
        await q("SAVEPOINT s");
        try {
          await q(sql, values);
          return null;
        } catch (e) {
          return e as pg.DatabaseError;
        } finally {
          await q("ROLLBACK TO s");
        }
      };
      const notNull = await fail("INSERT INTO chk (name) VALUES ($1)", [null]);
      expect(notNull).toMatchObject({ code: "23502", column: "name" });
      const check = await fail("INSERT INTO chk (name, price) VALUES ('a', $1)", ["-1"]);
      expect(check).toMatchObject({ code: "23514" });
      expect(check?.constraint).toContain("price");
      const domain = await fail("INSERT INTO chk (name, qty) VALUES ('a', $1)", ["0"]);
      expect(domain?.code).toBe("23514");
      const cast = await fail("INSERT INTO chk (name, price) VALUES ('a', $1)", ["abc"]);
      expect(cast?.code).toBe("22P02");
      expect(cast?.column).toBeUndefined(); // no column named: the cells are cast one by one to find it
      const long = await fail("INSERT INTO chk (name, price) VALUES ('a', $1)", ["123456789"]);
      expect(long?.code).toBe("22003");
    });
  });

  it("finds every failing row of a large batch by splitting it, in few statements", async () => {
    const rows = 20_000;
    const bad = new Set([77, 5_000, 5_001, 19_999]);
    let statements = 0;
    const result = await rolledBack(async () => {
      await checkingCopy();
      const insert = async (from: number, to: number): Promise<number[]> => {
        statements += 1;
        await q("SAVEPOINT b");
        try {
          const names: string[] = [];
          const prices: (string | null)[] = [];
          for (let i = from; i < to; i++) {
            names.push(`n${i}`);
            prices.push(bad.has(i) ? "-1" : "1.00");
          }
          await q("INSERT INTO chk (name, price) SELECT * FROM unnest($1::text[], $2::numeric[])", [
            names,
            prices,
          ]);
          await q("RELEASE b");
          return [];
        } catch {
          await q("ROLLBACK TO b");
          if (to - from === 1) return [from];
          const mid = Math.floor((from + to) / 2);
          return [...(await insert(from, mid)), ...(await insert(mid, to))];
        }
      };
      return insert(0, rows);
    });
    expect(result.sort((a, b) => a - b)).toEqual([...bad].sort((a, b) => a - b));
    // 4 failing rows in 20,000: a few hundred statements at most, not 20,000.
    expect(statements).toBeLessThan(200);
  }, 60_000);

  it("finds the existing rows a new row collides with, with a read-only query", async () => {
    await rolledBack(async () => {
      await checkingCopy();
      await q(
        "INSERT INTO chk (name, email, parent_id) VALUES ('a', 'taken@x.test', 99), ('b', 'free@x.test', 1)",
      );
      const unique = await q(
        "SELECT count(*)::int AS n FROM chk c WHERE EXISTS (SELECT 1 FROM v.target t WHERE t.email = c.email)",
      );
      expect(unique.rows[0]!.n).toBe(1);
      const orphan = await q(
        "SELECT count(*)::int AS n FROM chk c WHERE c.parent_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM v.parent p WHERE p.id = c.parent_id)",
      );
      expect(orphan.rows[0]!.n).toBe(1);
    });
  });
});
