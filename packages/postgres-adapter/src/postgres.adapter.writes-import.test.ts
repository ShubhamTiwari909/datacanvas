/**
 * Import (`insert_rows`) against a real PostgreSQL (`docs/advanced-data-workspace-plan.md`, section 9; decision
 * 160): rows in batches of 500, one statement each (`INSERT ... SELECT ... FROM unnest(arrays)`, every value bound
 * and cast in the database), all in one transaction. Every batch must insert exactly the rows it was planned for
 * or nothing is added; a cancel between batches rolls back too.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway database.
 */
import {
  DatabaseError,
  IMPORT_BATCH_ROWS,
  IMPORT_MAX_COLUMNS,
  IMPORT_MAX_ROWS,
  statementText,
  type Change,
  type TableRef,
} from "@datacanvas/database-core";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { PostgresAdapter } from "./postgres.adapter.js";
import { createTestDatabase, testDatabaseUrl, type TestDatabase } from "./testing/index.js";

const SECRET = "hunter2-SECRET-VALUE";

const SQL = `
  CREATE TABLE i_items (
    id int PRIMARY KEY, name varchar(10), qty int CHECK (qty >= 0), note text,
    made timestamptz NOT NULL DEFAULT now(), total int GENERATED ALWAYS AS (qty * 2) STORED
  );
  CREATE TABLE i_serial (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL, tag text DEFAULT 'none');
  CREATE TABLE i_always (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v text);
  CREATE TABLE i_audit (what text);
  CREATE FUNCTION i_audit_fn() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN INSERT INTO i_audit VALUES (TG_OP); RETURN NEW; END $$;
  CREATE TABLE i_trig (id int PRIMARY KEY, v text);
  CREATE TRIGGER i_trig_any AFTER INSERT ON i_trig FOR EACH ROW EXECUTE PROCEDURE i_audit_fn();
  CREATE FUNCTION i_swallow() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN IF NEW.v = 'skip' THEN RETURN NULL; END IF; RETURN NEW; END $$;
  CREATE TABLE i_swallowing (id int PRIMARY KEY, v text);
  CREATE TRIGGER i_swallow_it BEFORE INSERT ON i_swallowing FOR EACH ROW EXECUTE PROCEDURE i_swallow();
  CREATE TABLE i_parent (id int PRIMARY KEY);
  INSERT INTO i_parent VALUES (1), (2);
  CREATE TABLE i_child (id int PRIMARY KEY, parent_id int REFERENCES i_parent (id), other_id int REFERENCES i_parent (id));
  CREATE TABLE i_part (id int, region text, PRIMARY KEY (id, region)) PARTITION BY LIST (region);
  CREATE TABLE i_part_eu PARTITION OF i_part FOR VALUES IN ('eu');
  CREATE TABLE i_part_us PARTITION OF i_part FOR VALUES IN ('us');
  CREATE TABLE i_nokey (v text);
  CREATE TABLE "i ""odd"" ; table" ("select" int PRIMARY KEY, "a""b" text);
  CREATE VIEW i_view AS SELECT id FROM i_items;
`;

describe.skipIf(!testDatabaseUrl())("PostgresAdapter import", () => {
  let db: TestDatabase;
  let adapter: PostgresAdapter;
  let sql: pg.Client;
  const ref = (name: string): TableRef => ({ schema: "public", name });
  const importRows = (
    table: string,
    columns: string[],
    rows: Array<Array<string | null>>,
  ): Change => ({ kind: "insert_rows", table: ref(table), columns, rows });
  const q = async <T = Record<string, unknown>>(text: string): Promise<T[]> =>
    (await sql.query(text)).rows as T[];
  const count = async (table: string): Promise<number> =>
    Number((await q(`SELECT count(*)::int AS n FROM ${table}`))[0]!.n);
  const items = (n: number, from = 1): Array<Array<string | null>> =>
    Array.from({ length: n }, (_, i) => [String(from + i), `n${from + i}`, String(i), `note ${i}`]);

  async function failure(work: Promise<unknown>): Promise<DatabaseError> {
    const error = await work.then(
      () => null,
      (e: unknown) => e,
    );
    expect(error).toBeInstanceOf(DatabaseError);
    const failed = error as DatabaseError;
    for (const text of [failed.message, JSON.stringify(failed), String(failed)]) {
      expect(text).not.toContain(SECRET);
    }
    return failed;
  }

  beforeAll(async () => {
    db = await createTestDatabase();
    const { host, port, username, password } = db.connection;
    sql = new pg.Client({ host, port, user: username, password, database: db.dbName });
    await sql.connect();
    await sql.query(SQL);
    adapter = new PostgresAdapter(db.connection);
    await adapter.connect();
  }, 60_000);
  afterAll(async () => {
    await adapter?.disconnect();
    await sql?.end().catch(() => {});
    await db?.dispose().catch(() => {});
  });

  it("adds the rows in batches, in one transaction, and every row arrives as it was given", async () => {
    await sql.query("TRUNCATE i_items");
    const rows = items(IMPORT_BATCH_ROWS * 2 + 1);
    const plan = await adapter.previewChange(
      importRows("i_items", ["id", "name", "qty", "note"], rows),
    );
    expect(plan.statements).toHaveLength(3);
    expect(plan.statements.map((s) => s.expectRows)).toEqual([
      IMPORT_BATCH_ROWS,
      IMPORT_BATCH_ROWS,
      1,
    ]);
    expect(plan.destructive).toBe(false);
    expect(plan.effect).toContain("1,001 rows");
    expect(plan.effect).toContain("3 batches");
    expect(plan.effect).toContain("every row is added or none is");
    expect((await adapter.applyChange(plan)).rowCount).toBe(1001);
    expect(await count("i_items")).toBe(1001);
    expect(
      await q(
        "SELECT id, name, qty, note FROM i_items WHERE id IN (1, 500, 501, 1001) ORDER BY id",
      ),
    ).toEqual([
      { id: 1, name: "n1", qty: 0, note: "note 0" },
      { id: 500, name: "n500", qty: 499, note: "note 499" },
      { id: 501, name: "n501", qty: 500, note: "note 500" },
      { id: 1001, name: "n1001", qty: 1000, note: "note 1000" },
    ]);
  });

  it("shows one statement for the batches, with how many times it runs", async () => {
    const plan = await adapter.previewChange(
      importRows(
        "i_items",
        ["id", "name"],
        items(1200, 5000).map((r) => [r[0]!, r[1]!]),
      ),
    );
    const text = statementText(plan);
    // The statement is the same text for every batch (the values are arrays), the last one included.
    expect(text.match(/INSERT INTO/g)).toHaveLength(1);
    expect(text).toContain("the same statement runs for each of 3 batches of up to 500 rows");
    expect(text).not.toContain("n5000");
  });

  it("keeps NULL apart from the empty string, and every awkward character as it is", async () => {
    await sql.query("TRUNCATE i_items");
    const tricky = [
      "quote ' and \" and \\ and ,",
      "line\nbreak\r\n",
      "ünï 日本語 🙂",
      "  spaced  ",
      "{braces}",
      "NULL",
    ];
    const rows = [
      ["1", null, null, ""],
      ["2", "", "5", null],
      ...tricky.map((t, i) => [String(10 + i), "x", "1", t]),
    ];
    await adapter.applyChange(
      await adapter.previewChange(importRows("i_items", ["id", "name", "qty", "note"], rows)),
    );
    const got = await q<{
      id: number;
      name: string | null;
      qty: number | null;
      note: string | null;
    }>("SELECT id, name, qty, note FROM i_items ORDER BY id");
    expect(got[0]).toEqual({ id: 1, name: null, qty: null, note: "" });
    expect(got[1]).toEqual({ id: 2, name: "", qty: 5, note: null });
    expect(got.slice(2).map((r) => r.note)).toEqual(tricky);
  });

  it("adds nothing when one row of a later batch is refused, and says so without the value", async () => {
    await sql.query("TRUNCATE i_items");
    const rows = items(1200);
    rows[750] = ["751", "n751", `abc-${SECRET}`, "bad quantity"];
    const plan = await adapter.previewChange(
      importRows("i_items", ["id", "name", "qty", "note"], rows),
    );
    const error = await failure(adapter.applyChange(plan));
    expect(error.code).toBe("invalid_value");
    expect(await count("i_items")).toBe(0);
  });

  it("adds nothing for a NOT NULL column that is empty", async () => {
    await sql.query("TRUNCATE i_serial");
    const rows: Array<Array<string | null>> = Array.from({ length: 700 }, (_, i) => [`v${i}`]);
    rows[650] = [null];
    const error = await failure(
      adapter.applyChange(await adapter.previewChange(importRows("i_serial", ["v"], rows))),
    );
    expect(error.code).toBe("not_null_violation");
    expect(await count("i_serial")).toBe(0);
  });

  it("adds nothing when a key is already taken, or repeated within the file, or a CHECK or a length refuses", async () => {
    await sql.query("TRUNCATE i_items");
    await sql.query("INSERT INTO i_items (id, name, qty) VALUES (900, 'taken', 1)");
    const cases: Array<[Array<Array<string | null>>, string]> = [
      [[...items(600), ["900", "x", "1", "taken id"]], "unique_violation"],
      [[...items(600), ["10", "dup", "1", "in the file"]], "unique_violation"],
      [[...items(600), ["7000", "x", "-1", "check"]], "check_violation"],
      [[...items(600), ["7001", "this name is too long", "1", "length"]], "invalid_value"],
    ];
    for (const [rows, code] of cases) {
      const error = await failure(
        adapter.applyChange(
          await adapter.previewChange(importRows("i_items", ["id", "name", "qty", "note"], rows)),
        ),
      );
      expect(error.code).toBe(code);
      expect(await count("i_items")).toBe(1);
    }
  });

  it("adds nothing when a row has a foreign key that points nowhere, and warns that the keys are checked", async () => {
    await sql.query("TRUNCATE i_child");
    const rows = [
      ["1", "1", "2"],
      ["2", "99", "1"],
    ];
    const plan = await adapter.previewChange(
      importRows("i_child", ["id", "parent_id", "other_id"], rows),
    );
    expect(plan.warnings.find((w) => w.code === "scan")?.message).toContain("2 foreign keys");
    expect((await failure(adapter.applyChange(plan))).code).toBe("foreign_key_violation");
    expect(await count("i_child")).toBe(0);
  });

  it("leaves a column that is not given to the database: a default, an identity, a generated value", async () => {
    await sql.query("TRUNCATE i_serial RESTART IDENTITY");
    const plan = await adapter.previewChange(importRows("i_serial", ["v"], [["a"], ["b"], ["c"]]));
    expect(plan.effect).toContain("tag gets its default");
    expect(plan.effect).toContain("id is filled in by the database");
    await adapter.applyChange(plan);
    expect(await q("SELECT id, v, tag FROM i_serial ORDER BY id")).toEqual([
      { id: 1, v: "a", tag: "none" },
      { id: 2, v: "b", tag: "none" },
      { id: 3, v: "c", tag: "none" },
    ]);
    await sql.query("TRUNCATE i_items");
    await adapter.applyChange(
      await adapter.previewChange(importRows("i_items", ["id", "qty"], [["1", "4"]])),
    );
    expect(await q("SELECT total FROM i_items")).toEqual([{ total: 8 }]);
  });

  it("refuses what cannot be imported: a generated column, an identity that is always generated, an unknown column", async () => {
    const refused = async (change: Change) => (await failure(adapter.previewChange(change))).code;
    expect(await refused(importRows("i_items", ["id", "total"], [["1", "2"]]))).toBe(
      "invalid_change",
    );
    expect(await refused(importRows("i_always", ["id", "v"], [["1", "a"]]))).toBe("invalid_change");
    expect(await refused(importRows("i_items", ["id", "nope"], [["1", "a"]]))).toBe(
      "invalid_change",
    );
    expect(await refused(importRows("i_items", ['id"; DROP TABLE i_items; --'], [["1"]]))).toBe(
      "invalid_change",
    );
  });

  it("refuses a request that does not fit: no rows, a column twice, a row of the wrong length, too many rows or columns", async () => {
    const refused = async (change: Change) => (await failure(adapter.previewChange(change))).code;
    expect(await refused(importRows("i_items", ["id"], []))).toBe("invalid_change");
    expect(await refused(importRows("i_items", [], [["1"]]))).toBe("invalid_change");
    expect(await refused(importRows("i_items", ["id", "id"], [["1", "2"]]))).toBe("invalid_change");
    expect(await refused(importRows("i_items", ["id", "name"], [["1"]]))).toBe("invalid_change");
    const wide = Array.from({ length: IMPORT_MAX_COLUMNS + 1 }, (_, i) => `c${i}`);
    expect(await refused(importRows("i_items", wide, [wide.map(() => "x")]))).toBe(
      "invalid_change",
    );
    const tall = Array.from({ length: IMPORT_MAX_ROWS + 1 }, () => ["1"]);
    expect(await refused(importRows("i_items", ["id"], tall))).toBe("invalid_change");
  }, 60_000);

  it("names a trigger that runs for each row, and it does", async () => {
    await sql.query("TRUNCATE i_trig, i_audit");
    const rows = Array.from({ length: 600 }, (_, i) => [String(i + 1), "v"]);
    const plan = await adapter.previewChange(importRows("i_trig", ["id", "v"], rows));
    expect(plan.warnings.find((w) => w.code === "triggers")?.message).toContain(
      "for each of the 600 rows",
    );
    await adapter.applyChange(plan);
    expect(await count("i_audit")).toBe(600);
  });

  it("rolls everything back when a trigger swallows a row, because a batch must add exactly the rows it was planned for", async () => {
    await sql.query("TRUNCATE i_swallowing");
    const rows = Array.from({ length: 900 }, (_, i) => [
      String(i + 1),
      i === 700 ? "skip" : "keep",
    ]);
    const plan = await adapter.previewChange(importRows("i_swallowing", ["id", "v"], rows));
    const error = await failure(adapter.applyChange(plan));
    expect(error.code).toBe("unexpected");
    expect(await count("i_swallowing")).toBe(0);
  });

  it("stops between batches when it is cancelled, and nothing is kept", async () => {
    await sql.query("TRUNCATE i_items");
    const plan = await adapter.previewChange(
      importRows(
        "i_items",
        ["id", "name"],
        items(2600).map((r) => [r[0]!, r[1]!]),
      ),
    );
    expect(plan.statements).toHaveLength(6);
    let looked = 0;
    // Cancelled after the third batch was run.
    const signal = {
      get aborted() {
        looked += 1;
        return looked > 3;
      },
    };
    await failure(adapter.applyChange(plan, signal));
    expect(await count("i_items")).toBe(0);
    // And a cancel that never comes changes nothing about a normal apply.
    expect((await adapter.applyChange(plan, { aborted: false })).rowCount).toBe(2600);
  });

  it("refuses a plan whose table was replaced between preview and apply, and writes nothing", async () => {
    await sql.query("CREATE TABLE i_swap (id int PRIMARY KEY, v text)");
    const plan = await adapter.previewChange(
      importRows(
        "i_swap",
        ["id", "v"],
        [
          ["1", "a"],
          ["2", "b"],
        ],
      ),
    );
    await sql.query("DROP TABLE i_swap");
    await sql.query("CREATE TABLE i_swap (id int PRIMARY KEY, v text)");
    await failure(adapter.applyChange(plan));
    expect(await count("i_swap")).toBe(0);
  });

  it("works on a partitioned table, a table with awkward names, and refuses a view and a table without a key", async () => {
    await adapter.applyChange(
      await adapter.previewChange(
        importRows(
          "i_part",
          ["id", "region"],
          [
            ["1", "eu"],
            ["2", "us"],
          ],
        ),
      ),
    );
    expect(await count("i_part_eu")).toBe(1);
    expect(await count("i_part_us")).toBe(1);
    // A row that fits no partition is refused by the database, and nothing is kept.
    expect(
      (
        await failure(
          adapter.applyChange(
            await adapter.previewChange(
              importRows(
                "i_part",
                ["id", "region"],
                [
                  ["3", "eu"],
                  ["4", "asia"],
                ],
              ),
            ),
          ),
        )
      ).code,
    ).toBeTruthy();
    expect(await count("i_part")).toBe(2);
    await adapter.applyChange(
      await adapter.previewChange({
        kind: "insert_rows",
        table: ref('i "odd" ; table'),
        columns: ["select", 'a"b'],
        rows: [["1", "x"]],
      }),
    );
    expect(await q('SELECT "select", "a""b" AS ab FROM "i ""odd"" ; table"')).toEqual([
      { select: 1, ab: "x" },
    ]);
    expect((await failure(adapter.previewChange(importRows("i_view", ["id"], [["1"]])))).code).toBe(
      "not_editable",
    );
    expect((await failure(adapter.previewChange(importRows("i_nokey", ["v"], [["1"]])))).code).toBe(
      "not_editable",
    );
  });

  it("imports 100,000 rows in one transaction, and says how long it took", async () => {
    await sql.query("TRUNCATE i_items");
    const rows = Array.from({ length: IMPORT_MAX_ROWS }, (_, i) => [
      String(i + 1),
      `n${i % 1000}`,
      String(i % 50),
      `a note for row ${i + 1}, with a comma and a "quote"`,
    ]);
    const started = Date.now();
    const plan = await adapter.previewChange(
      importRows("i_items", ["id", "name", "qty", "note"], rows),
    );
    const planned = Date.now() - started;
    const applied = await adapter.applyChange(plan);
    const total = Date.now() - started;
    expect(applied.rowCount).toBe(IMPORT_MAX_ROWS);
    expect(await count("i_items")).toBe(IMPORT_MAX_ROWS);
    expect(plan.statements).toHaveLength(IMPORT_MAX_ROWS / IMPORT_BATCH_ROWS);
    // The measure that decides batched INSERT against COPY (decision 160): printed, and bounded generously.
    console.log(
      `import of ${IMPORT_MAX_ROWS} rows: planned in ${planned} ms, whole in ${total} ms`,
    );
    expect(total).toBeLessThan(120_000);
  }, 180_000);
});
