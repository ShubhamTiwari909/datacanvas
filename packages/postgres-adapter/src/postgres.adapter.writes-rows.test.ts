/**
 * Row changes against a real PostgreSQL (`docs/data-editing-plan.md`, section 9):
 * update, insert and delete by key, awkward names, every allow-list type, NULL
 * against the empty string, the conflict check, fixed error messages that never
 * repeat a value, triggers and cascades, tables that cannot be edited, a
 * partitioned table, row-level security, the lock timeout, and the role check.
 *
 * Skipped unless DATACANVAS_TEST_PG_URL is set. Runs in its own throwaway
 * database; a throwaway role is created (and dropped) for the role tests.
 */
