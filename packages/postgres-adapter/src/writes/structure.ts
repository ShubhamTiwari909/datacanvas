/**
 * Changes of structure: creating a table and altering one (plan 6.5 and 6.6,
 * decisions 130 to 133).
 *
 * Every statement is built from quoted names, types from the allow-list
 * (`renderType`), structured defaults (`renderDefault`) and quoted literals.
 * There is no expression, no `USING`, no check constraint, no
 * `CONCURRENTLY`, and never `CASCADE` on a drop: a drop that something
 * depends on is refused and the dependents are named. (`ON DELETE CASCADE` in a
 * foreign key is a referential action the person chose, not a drop.)
 */
