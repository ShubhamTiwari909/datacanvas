// --------------------------------------------------------------- builders ---

const stmt = (text: string): PlannedStatement => ({ text, values: [] });

function checkNewName(name: string, what: string): void {
  if (!isValidNewIdentifier(name)) {
    throw invalidChange(
      `The ${what} name is not valid: it must be 1 to 63 bytes, with no NUL character and no space at either end.`,
    );
  }
}

/** `"name" type [GENERATED ... AS IDENTITY] [NOT NULL] [DEFAULT ...]`. */
export function buildColumnDefinition(
  column: ColumnDefinition,
  uuidFunction: string | null,
): string {
  checkNewName(column.name, "column");
  const type = renderType(column.type);
  const parts = [quoteIdentifier(column.name), type];
  if (column.identity !== null) {
    if (!canBeIdentity(column.type)) {
      throw invalidChange(`${column.name}: only smallint, integer and bigint can be an identity.`);
    }
    if (column.default.kind !== "none") {
      throw invalidChange(`${column.name}: an identity column cannot also have a default.`);
    }
    parts.push(
      column.identity === "always"
        ? "GENERATED ALWAYS AS IDENTITY"
        : "GENERATED BY DEFAULT AS IDENTITY",
    );
  } else if (!column.nullable) {
    parts.push("NOT NULL");
  }
  const defaultSql = renderDefault(column.default, type, renderBaseType(column.type), uuidFunction);
  if (defaultSql !== null) parts.push(`DEFAULT ${defaultSql}`);
  return parts.join(" ");
}

export function buildForeignKey(fk: ForeignKeyDefinition): string {
  return `FOREIGN KEY (${columnList(fk.columns)}) REFERENCES ${quoteQualified(
    fk.references.schema,
    fk.references.table,
  )} (${columnList(fk.references.columns)}) ON DELETE ${renderAction(fk.onDelete)} ON UPDATE ${renderAction(fk.onUpdate)}`;
}

function commentStatement(target: string, comment: string | null): PlannedStatement[] {
  if (comment === null || comment === "") return [];
  return [stmt(`COMMENT ON ${target} IS ${quoteLiteral(comment)}`)];
}

export function buildCreateTable(
  change: CreateTableChange,
  uuidFunction: string | null,
): PlannedStatement[] {
  checkNewName(change.name, "table");
  const table = quoteQualified(change.schema, change.name);
  const lines = change.columns.map((c) => buildColumnDefinition(c, uuidFunction));
  if (change.primaryKey.length > 0) lines.push(`PRIMARY KEY (${columnList(change.primaryKey)})`);
  for (const unique of change.unique) lines.push(`UNIQUE (${columnList(unique)})`);
  for (const fk of change.foreignKeys) lines.push(buildForeignKey(fk));
  return [
    stmt(`CREATE TABLE ${table} (\n  ${lines.join(",\n  ")}\n)`),
    ...commentStatement(`TABLE ${table}`, change.comment),
    ...change.columns.flatMap((c) =>
      commentStatement(`COLUMN ${table}.${quoteIdentifier(c.name)}`, c.comment),
    ),
  ];
}

const alter = (table: TableRef, action: string): PlannedStatement =>
  stmt(`ALTER TABLE ${quoteQualified(table.schema, table.name)} ${action}`);

// ---------------------------------------------------------------- helpers ---

const LOCK_WARNING: ChangeWarning = {
  code: "lock",
  message:
    "This takes a lock that blocks every read and write of the table until the change is committed.",
};

function scanWarning(what: string): ChangeWarning {
  return { code: "scan", message: `This reads every row of the table to ${what}.` };
}

function rewriteWarning(table: CatalogTable): ChangeWarning {
  const rows =
    table.reltuples >= 0
      ? ` (about ${Math.round(table.reltuples).toLocaleString("en-US")} rows by the planner's estimate)`
      : "";
  return {
    code: "rewrite",
    message: `This may rewrite the whole table${rows}, holding the lock until it is done.`,
  };
}

const where = (table: TableRef): string => displayName(table.schema, table.name);

async function requireTable(db: Queryable, ref: TableRef): Promise<CatalogTable> {
  const table = await loadTable(db, ref);
  if (!table) throw new DatabaseError("not_found");
  if (table.relkind !== "r" && table.relkind !== "p") {
    throw new DatabaseError("not_editable", {
      message:
        "Only the structure of a table can be changed here, not that of a view or a foreign table.",
    });
  }
  return table;
}

function requireColumn(table: CatalogTable, name: string): CatalogColumn {
  const column = table.columns.find((c) => c.name === name);
  if (!column) throw invalidChange(`The column ${name} does not exist (any more).`);
  return column;
}

function requireColumns(table: CatalogTable, names: readonly string[]): void {
  if (new Set(names).size !== names.length) throw invalidChange("A column is listed twice.");
  for (const name of names) requireColumn(table, name);
}

async function uuidFunctionSql(db: Queryable): Promise<string | null> {
  const found = await findUuidFunction(db);
  return found ? qualifiedFunction(found.schema, "gen_random_uuid") : null;
}

/** Check that a literal default is accepted by the column's type (in a savepoint, nothing changes). */
async function checkLiteral(
  db: Queryable,
  value: string,
  typeSql: string,
  column: string,
): Promise<void> {
  if (value.includes("\0")) throw invalidChange("A text value cannot contain a NUL character.");
  await db.query("SAVEPOINT dc_default_check");
  try {
    await db.query(`SELECT CAST($1 AS ${typeSql})`, [value]);
    await db.query("RELEASE SAVEPOINT dc_default_check");
  } catch (error) {
    await db.query("ROLLBACK TO SAVEPOINT dc_default_check");
    const code =
      typeof error === "object" && error !== null ? (error as { code?: unknown }).code : undefined;
    if (
      typeof code === "string" &&
      (code.startsWith("22") || code === "23514" || code === "23502")
    ) {
      throw new DatabaseError("invalid_value", {
        message: `The default for ${column} is not a valid ${typeSql}.`,
        cause: error,
      });
    }
    throw error;
  }
}

async function checkColumnDefault(db: Queryable, column: ColumnDefinition): Promise<void> {
  if (column.default.kind === "literal") {
    await checkLiteral(db, column.default.value, renderType(column.type), column.name);
  }
}

/** A foreign key's target must exist and be covered by a primary key or unique index. */
async function checkForeignKeyTarget(
  db: Queryable,
  fk: ForeignKeyDefinition,
  self: { schema: string; name: string; keys: string[][] } | null,
): Promise<void> {
  if (new Set(fk.columns).size !== fk.columns.length) {
    throw invalidChange("A foreign key lists a column twice.");
  }
  if (fk.columns.length !== fk.references.columns.length) {
    throw invalidChange("A foreign key needs as many referenced columns as columns.");
  }
  const target = fk.references;
  if (self && target.schema === self.schema && target.table === self.name) {
    const wanted = [...target.columns].sort().join("\0");
    if (!self.keys.some((k) => [...k].sort().join("\0") === wanted)) {
      throw invalidChange(
        "A foreign key to the new table itself must point at its primary key or one of its unique keys.",
      );
    }
    return;
  }
  const table = await loadTable(db, { schema: target.schema, name: target.table });
  if (!table || (table.relkind !== "r" && table.relkind !== "p")) {
    throw invalidChange(`The table ${displayName(target.schema, target.table)} does not exist.`);
  }
  requireColumns(table, target.columns);
  if (!(await hasUniqueKeyOn(db, table.oid, target.columns))) {
    throw invalidChange(
      `The columns a foreign key points at (${listWords(target.columns)} of ${displayName(target.schema, target.table)}) must be its primary key or a unique key.`,
    );
  }
}

function plan(
  change: StructureChange,
  statements: PlannedStatement[],
  effect: string,
  warnings: ChangeWarning[],
): PlannedChange {
  const destructive = DESTRUCTIVE_CHANGE_KINDS.includes(change.kind);
  return {
    change,
    statements,
    expect: "any",
    category: "structure",
    effect,
    warnings: destructive
      ? [...warnings, { code: "destructive", message: "This cannot be undone." }]
      : warnings,
    destructive,
  };
}

// --------------------------------------------------------------- planning ---

async function planCreateTable(db: Queryable, change: CreateTableChange): Promise<PlannedChange> {
  if (!(await schemaExists(db, change.schema))) {
    throw new DatabaseError("not_found", { message: "The schema does not exist." });
  }
  checkNewName(change.name, "table");
  if (await relationNameTaken(db, change.schema, change.name)) {
    throw new DatabaseError("already_exists", {
      message: `Something called ${where({ schema: change.schema, name: change.name })} already exists.`,
    });
  }
  if (change.columns.length === 0) throw invalidChange("A table needs at least one column.");
  const names = change.columns.map((c) => c.name);
  if (new Set(names).size !== names.length) throw invalidChange("Two columns have the same name.");
  const known = (list: readonly string[], what: string) => {
    if (new Set(list).size !== list.length)
      throw invalidChange(`The ${what} lists a column twice.`);
    for (const c of list) {
      if (!names.includes(c))
        throw invalidChange(`The ${what} names ${c}, which is not a column of the new table.`);
    }
  };
  known(change.primaryKey, "primary key");
  for (const u of change.unique) {
    if (u.length === 0) throw invalidChange("A unique key needs at least one column.");
    known(u, "unique key");
  }
  const keys = [...(change.primaryKey.length > 0 ? [change.primaryKey] : []), ...change.unique];
  for (const fk of change.foreignKeys) {
    known(fk.columns, "foreign key");
    await checkForeignKeyTarget(db, fk, { schema: change.schema, name: change.name, keys });
  }
  for (const column of change.columns) await checkColumnDefault(db, column);
  const statements = buildCreateTable(change, await uuidFunctionSql(db));
  const warnings: ChangeWarning[] = [];
  if (change.foreignKeys.length > 0) {
    warnings.push({
      code: "lock",
      message: "Creating the foreign keys briefly locks the tables they point at against writes.",
    });
  }
  if (change.primaryKey.length === 0) {
    warnings.push({
      code: "may_fail",
      message:
        "Without a primary key (or a unique key on NOT NULL columns), the rows of this table cannot be edited here.",
    });
  }
  return plan(
    change,
    statements,
    `Creates the table ${where({ schema: change.schema, name: change.name })} with ${change.columns.length === 1 ? "one column" : `${change.columns.length} columns`}.`,
    warnings,
  );
}

/** The columns of the table that an alteration names (they must be the same columns at apply). */
function namedColumns(change: Exclude<StructureChange, CreateTableChange>): string[] {
  switch (change.kind) {
    case "rename_column":
    case "alter_column_type":
    case "set_nullable":
    case "set_default":
    case "drop_column":
      return [change.column];
    case "add_primary_key":
    case "add_unique":
    case "create_index":
      return change.columns;
    case "add_foreign_key":
      return change.foreignKey.columns;
    default:
      return [];
  }
}

/**
 * Plan an alteration and pin what it was planned against: the table as it was
 * when it was loaded (before any check), locked at apply in the mode the
 * statement itself takes (a plain CREATE INDEX only blocks writes; every
 * other form blocks reads too, as the preview already says), and, for a
 * foreign key, the table it points at.
 */
async function planAlter(
  db: Queryable,
  change: Exclude<StructureChange, CreateTableChange>,
): Promise<PlannedChange> {
  const table = await requireTable(db, change.table);
  const planned = await planAlterOn(db, change, table);
  const relations = [
    guardRelation(
      table,
      namedColumns(change),
      change.kind === "create_index" ? "share" : "access_exclusive",
    ),
  ];
  if (change.kind === "add_foreign_key") {
    const target = change.foreignKey.references;
    const loaded = await loadTable(db, { schema: target.schema, name: target.table });
    if (loaded) relations.push(guardRelation(loaded, target.columns, "none"));
  }
  return { ...planned, guard: { relations } };
}

async function planAlterOn(
  db: Queryable,
  change: Exclude<StructureChange, CreateTableChange>,
  table: CatalogTable,
): Promise<PlannedChange> {
  const ref = change.table;
  const name = where(ref);

  switch (change.kind) {
    case "add_column": {
      checkNewName(change.column.name, "column");
      if (table.columns.some((c) => c.name === change.column.name)) {
        throw new DatabaseError("already_exists", {
          message: `${name} already has a column ${change.column.name}.`,
        });
      }
      await checkColumnDefault(db, change.column);
      const definition = buildColumnDefinition(change.column, await uuidFunctionSql(db));
      const warnings = [LOCK_WARNING];
      const c = change.column;
      if (!c.nullable && c.identity === null && c.default.kind === "none") {
        warnings.push({
          code: "may_fail",
          message: "A NOT NULL column without a default cannot be added while the table has rows.",
        });
      }
      if (c.identity !== null || c.default.kind === "gen_random_uuid")
        warnings.push(rewriteWarning(table));
      return plan(
        change,
        [
          alter(ref, `ADD COLUMN ${definition}`),
          ...commentStatement(
            `COLUMN ${quoteQualified(ref.schema, ref.name)}.${quoteIdentifier(c.name)}`,
            c.comment,
          ),
        ],
        `Adds the column ${c.name} to ${name}.`,
        warnings,
      );
    }

    case "rename_column": {
      const column = requireColumn(table, change.column);
      checkNewName(change.to, "column");
      if (table.columns.some((c) => c.name === change.to)) {
        throw new DatabaseError("already_exists", {
          message: `${name} already has a column ${change.to}.`,
        });
      }
      const views = await listDependentViews(db, table.oid, column.attnum);
      return plan(
        change,
        [
          alter(
            ref,
            `RENAME COLUMN ${quoteIdentifier(change.column)} TO ${quoteIdentifier(change.to)}`,
          ),
        ],
        `Renames the column ${change.column} of ${name} to ${change.to}.`,
        [renamedWarning(views), LOCK_WARNING],
      );
    }

    case "rename_table": {
      checkNewName(change.to, "table");
      if (await relationNameTaken(db, ref.schema, change.to)) {
        throw new DatabaseError("already_exists", {
          message: `Something called ${where({ schema: ref.schema, name: change.to })} already exists.`,
        });
      }
      const views = await listDependentViews(db, table.oid, null);
      return plan(
        change,
        [alter(ref, `RENAME TO ${quoteIdentifier(change.to)}`)],
        `Renames the table ${name} to ${change.to}.`,
        [renamedWarning(views), LOCK_WARNING],
      );
    }

    case "alter_column_type": {
      const column = requireColumn(table, change.column);
      const typeSql = renderType(change.type);
      const target = await resolveType(db, renderBaseType(change.type));
      if (!target) throw invalidChange("This type does not exist on this server.");
      const sameType = target.oid === column.typeOid;
      const castable =
        sameType ||
        (!column.isArray &&
          target.category !== "A" &&
          (target.category === "S" ||
            (await hasAssignmentCast(db, column.rootTypeOid, target.oid))));
      if (!castable) {
        throw invalidChange(
          `PostgreSQL cannot convert ${column.dataType} to ${typeSql} on its own; this change would need a conversion expression, which is not offered.`,
        );
      }
      const views = await listDependentViews(db, table.oid, column.attnum);
      if (views.length > 0) {
        throw new DatabaseError("has_dependents", {
          message: `The type of ${change.column} cannot change while views use it: ${listWords(views)}. Nothing was changed.`,
        });
      }
      return plan(
        change,
        [alter(ref, `ALTER COLUMN ${quoteIdentifier(change.column)} TYPE ${typeSql}`)],
        `Changes the type of ${change.column} of ${name} from ${column.dataType} to ${typeSql}.`,
        [
          LOCK_WARNING,
          rewriteWarning(table),
          { code: "may_fail", message: "It fails if a value does not convert to the new type." },
        ],
      );
    }

    case "set_nullable": {
      const column = requireColumn(table, change.column);
      if (change.nullable) {
        const constraints = await listConstraints(db, table.oid);
        if (constraints.some((c) => c.type === "p" && c.columns.includes(column.name))) {
          throw invalidChange(
            `${column.name} is part of the primary key, so it cannot allow NULL.`,
          );
        }
        if (column.identity !== null)
          throw invalidChange(`${column.name} is an identity column, so it cannot allow NULL.`);
        return plan(
          change,
          [alter(ref, `ALTER COLUMN ${quoteIdentifier(column.name)} DROP NOT NULL`)],
          `Lets ${column.name} of ${name} be empty (NULL).`,
          [LOCK_WARNING],
        );
      }
      return plan(
        change,
        [alter(ref, `ALTER COLUMN ${quoteIdentifier(column.name)} SET NOT NULL`)],
        `Makes ${column.name} of ${name} required (NOT NULL).`,
        [
          LOCK_WARNING,
          scanWarning("check that no value is NULL"),
          { code: "may_fail", message: "It fails if a row has NULL in this column." },
        ],
      );
    }

    case "set_default": {
      const column = requireColumn(table, change.column);
      if (column.identity !== null || column.generated) {
        throw invalidChange(
          `${column.name} is filled by the database, so it cannot have a default.`,
        );
      }
      if (change.default.kind === "none") {
        return plan(
          change,
          [alter(ref, `ALTER COLUMN ${quoteIdentifier(column.name)} DROP DEFAULT`)],
          `Removes the default of ${column.name} of ${name}.`,
          [LOCK_WARNING],
        );
      }
      if (column.isArray && change.default.kind !== "literal") {
        throw invalidChange(`This kind of default does not fit a ${column.dataType} column.`);
      }
      if (change.default.kind === "literal") {
        await checkLiteral(db, change.default.value, column.dataType, column.name);
      }
      const sql = renderDefault(
        change.default,
        column.dataType,
        column.rootType,
        await uuidFunctionSql(db),
      );
      return plan(
        change,
        [alter(ref, `ALTER COLUMN ${quoteIdentifier(column.name)} SET DEFAULT ${sql}`)],
        `Sets the default of ${column.name} of ${name}; existing rows keep their values.`,
        [LOCK_WARNING],
      );
    }

    case "add_primary_key": {
      requireColumns(table, change.columns);
      const constraints = await listConstraints(db, table.oid);
      if (constraints.some((c) => c.type === "p"))
        throw invalidChange(`${name} already has a primary key.`);
      return plan(
        change,
        [alter(ref, `ADD PRIMARY KEY (${columnList(change.columns)})`)],
        `Adds a primary key on ${listWords(change.columns)} to ${name}.`,
        [
          LOCK_WARNING,
          scanWarning("build the key's index and check that its values are unique and not NULL"),
          { code: "may_fail", message: "It fails if two rows share a value or a value is NULL." },
        ],
      );
    }

    case "add_unique": {
      requireColumns(table, change.columns);
      return plan(
        change,
        [alter(ref, `ADD UNIQUE (${columnList(change.columns)})`)],
        `Adds a unique key on ${listWords(change.columns)} to ${name}.`,
        [
          LOCK_WARNING,
          scanWarning("build the key's index"),
          { code: "may_fail", message: "It fails if two rows share a value." },
        ],
      );
    }

    case "add_foreign_key": {
      requireColumns(table, change.foreignKey.columns);
      await checkForeignKeyTarget(db, change.foreignKey, null);
      const fk = change.foreignKey;
      return plan(
        change,
        [alter(ref, `ADD ${buildForeignKey(fk)}`)],
        `Adds a foreign key from ${listWords(fk.columns)} of ${name} to ${displayName(fk.references.schema, fk.references.table)}.`,
        [
          LOCK_WARNING,
          scanWarning("check that every value has a matching row"),
          { code: "may_fail", message: "It fails if a row points at a row that does not exist." },
        ],
      );
    }

    case "drop_constraint": {
      const constraints = await listConstraints(db, table.oid);
      const constraint = constraints.find((c) => c.name === change.constraint);
      if (!constraint) throw invalidChange(`${name} has no constraint ${change.constraint}.`);
      if (!["p", "u", "f"].includes(constraint.type)) {
        throw invalidChange(
          "Only a primary key, a unique key or a foreign key can be dropped here.",
        );
      }
      if (constraint.type !== "f" && constraint.indexOid !== "0") {
        const users = await foreignKeysUsingIndex(db, constraint.indexOid);
        if (users.length > 0) {
          throw new DatabaseError("has_dependents", {
            message: `Foreign keys depend on ${change.constraint}: ${listWords(users)}. Drop them first. Nothing was changed.`,
          });
        }
      }
      return plan(
        change,
        [alter(ref, `DROP CONSTRAINT ${quoteIdentifier(change.constraint)}`)],
        `Drops the constraint ${change.constraint} of ${name}.`,
        [LOCK_WARNING],
      );
    }

    case "create_index": {
      requireColumns(table, change.columns);
      const warnings: ChangeWarning[] = [
        {
          code: "lock",
          message:
            "The index is built with a plain CREATE INDEX: writes to the table wait until it is finished (reads continue).",
        },
        scanWarning("build the index"),
      ];
      if (change.unique) {
        warnings.push({ code: "may_fail", message: "It fails if two rows share a value." });
      }
      return plan(
        change,
        [
          stmt(
            `CREATE ${change.unique ? "UNIQUE " : ""}INDEX ON ${quoteQualified(ref.schema, ref.name)} (${columnList(change.columns)})`,
          ),
        ],
        `Creates ${change.unique ? "a unique" : "an"} index on ${listWords(change.columns)} of ${name}.`,
        warnings,
      );
    }

    case "drop_index": {
      const index = await findIndex(db, table.oid, change.index);
      if (!index) throw invalidChange(`${name} has no index ${change.index}.`);
      if (index.constraint) {
        throw invalidChange(
          `The index ${change.index} enforces the constraint ${index.constraint}; drop the constraint instead.`,
        );
      }
      const users = await foreignKeysUsingIndex(db, index.oid);
      if (users.length > 0) {
        throw new DatabaseError("has_dependents", {
          message: `Foreign keys depend on ${change.index}: ${listWords(users)}. Nothing was changed.`,
        });
      }
      return plan(
        change,
        [stmt(`DROP INDEX ${quoteQualified(ref.schema, change.index)}`)],
        `Drops the index ${change.index} of ${name}.`,
        [LOCK_WARNING],
      );
    }

    case "drop_column": {
      requireConfirm(change.confirm, ref);
      const column = requireColumn(table, change.column);
      if (table.columns.length === 1)
        throw invalidChange("A table's last column cannot be dropped here.");
      const dependents = await listDependents(db, table, column.attnum);
      if (dependents.length > 0) {
        throw new DatabaseError("has_dependents", {
          message: `${change.column} cannot be dropped while other things use it: ${listWords(dependents)}. Nothing was changed.`,
        });
      }
      return plan(
        change,
        [alter(ref, `DROP COLUMN ${quoteIdentifier(change.column)}`)],
        `Drops the column ${change.column} of ${name}, with every value in it.`,
        [LOCK_WARNING],
      );
    }

    case "drop_table": {
      requireConfirm(change.confirm, ref);
      const dependents = await listDependents(db, table, null);
      if (dependents.length > 0) {
        throw new DatabaseError("has_dependents", {
          message: `${name} cannot be dropped while other things use it: ${listWords(dependents)}. Nothing was changed.`,
        });
      }
      return plan(
        change,
        [stmt(`DROP TABLE ${quoteQualified(ref.schema, ref.name)}`)],
        `Drops the table ${name}, with all its rows.`,
        [LOCK_WARNING],
      );
    }

    default:
      throw invalidChange("This kind of change is not offered.");
  }
}

function requireConfirm(confirm: string, ref: TableRef): void {
  if (confirm !== ref.name) {
    throw invalidChange("Type the table's name exactly to confirm.");
  }
}

function renamedWarning(views: readonly string[]): ChangeWarning {
  return {
    code: "renamed",
    message:
      views.length > 0
        ? `Views keep working (${listWords(views)}), but queries, functions and application code that use the old name will break.`
        : "Queries, functions and application code that use the old name will break.",
  };
}

export function planStructureChange(
  db: Queryable,
  change: StructureChange,
): Promise<PlannedChange> {
  return change.kind === "create_table" ? planCreate(db, change) : planAlter(db, change);
}

/**
 * Plan a creation. There is no table to pin, but a foreign key binds to the
 * table it points at by name, so that table must be the same one at apply.
 */
async function planCreate(db: Queryable, change: CreateTableChange): Promise<PlannedChange> {
  const planned = await planCreateTable(db, change);
  const relations = [];
  for (const fk of change.foreignKeys) {
    const target = fk.references;
    if (target.schema === change.schema && target.table === change.name) continue; // the new table itself
    const loaded = await loadTable(db, { schema: target.schema, name: target.table });
    if (loaded) relations.push(guardRelation(loaded, target.columns, "none"));
  }
  return relations.length > 0 ? { ...planned, guard: { relations } } : planned;
}
