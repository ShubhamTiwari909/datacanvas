/**
 * Generate THIRD-PARTY-NOTICES.md: every runtime dependency (direct and
 * transitive) of the app and the packages, with its version, license and
 * source address. Development-only tools are not listed because they are not
 * shipped. Run with `npm run notices` after changing dependencies.
 *
 * Packages that offer a choice of licenses ("A OR B") are listed with the
 * option this project has chosen (see CHOICES below and docs/decisions.md).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "apps/web/package.json"));

/** License option chosen for dual-licensed packages (a legal decision, recorded in decisions.md). */
const CHOICES = { elkjs: "EPL-2.0" };

const manifests = [
  "apps/web",
  "packages/shared-types",
  "packages/database-core",
  "packages/postgres-adapter",
  "packages/canvas-engine",
  "packages/cli",
];

const found = new Map();
function repositoryOf(pkg) {
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  return (repo ?? pkg.homepage ?? "").replace(/^git\+/, "").replace(/\.git$/, "");
}
function visit(name, fromDir) {
  if (name.startsWith("@datacanvas/") || found.has(name)) return;
  let file;
  try {
    file = require.resolve(`${name}/package.json`, { paths: [fromDir] });
  } catch {
    file = path.join(root, "node_modules", name, "package.json");
  }
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(file, "utf8"));
  } catch {
    found.set(name, { name, version: "?", license: "UNKNOWN", repository: "" });
    return;
  }
  const license =
    typeof pkg.license === "string" ? pkg.license : JSON.stringify(pkg.license ?? "UNKNOWN");
  found.set(name, { name, version: pkg.version, license, repository: repositoryOf(pkg) });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, path.dirname(file));
}

for (const dir of manifests) {
  const pkg = JSON.parse(readFileSync(path.join(root, dir, "package.json"), "utf8"));
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, path.join(root, dir));
}

const rows = [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
const lines = [
  "# Third-party notices",
  "",
  "DataCanvas is licensed under the Apache License 2.0 (see `LICENSE`). It includes or depends on the third-party packages below, each under its own license. This file is generated by `npm run notices`; do not edit it by hand.",
  "",
  "## Packages used under a chosen license",
  "",
];
for (const [name, choice] of Object.entries(CHOICES)) {
  const row = found.get(name);
  if (!row) continue;
  lines.push(
    `- **${name}** ${row.version} is offered under "${row.license}". DataCanvas uses it under **${choice}**. Source: ${row.repository || "see the package"}. If you modify this package you must make those modifications available under ${choice}.`,
  );
}
lines.push(
  "",
  "## All runtime dependencies",
  "",
  "| Package | Version | License | Source |",
  "| --- | --- | --- | --- |",
);
for (const row of rows) {
  lines.push(`| ${row.name} | ${row.version} | ${row.license} | ${row.repository || ""} |`);
}
const unknown = rows.filter((r) => r.license === "UNKNOWN");
if (unknown.length)
  lines.push("", `Licenses could not be read for: ${unknown.map((r) => r.name).join(", ")}.`);
lines.push("");
writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), lines.join("\n"));
console.log(
  `Wrote THIRD-PARTY-NOTICES.md (${rows.length} packages${unknown.length ? `, ${unknown.length} unknown` : ""}).`,
);
